def generate(source: Path, out: Path) -> Generator:
    with source.open(encoding='utf-8') as fh:
        data = json.load(fh)
    gen = Generator(data)
    gen.build()
    (out / 'points.py').write_text(gen.render_points(), encoding='utf-8')
    (out / 'profiles.py').write_text(gen.render_profiles(), encoding='utf-8')
    (out / 'profile_builders.py').write_text(gen.render_builders(), encoding='utf-8')
    (out / '__init__.py').write_text(gen.render_init(), encoding='utf-8')
    return gen


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--source', type=Path, default=DEFAULT_SOURCE, help='IEEE 1815.2 test tool profile JSON (full.json)')
    parser.add_argument('--out', type=Path, default=HERE, help='package directory to write into')
    args = parser.parse_args(argv)
    gen = generate(args.source, args.out)
    n_points = sum(len(v) for v in gen.definitions.values())
