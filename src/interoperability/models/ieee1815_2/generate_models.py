"""Generate pydantic models and profile builders for the IEEE 1815.2 (MESA-DER) point list.

Source: the ``full.json`` profile of the IEEE 1815.2 test tool, vendored and reconciled at
``sources/ieee1815_2/full.json`` (see ``SOURCE.md`` beside it), which lists every
AI / AO / BI / BO / counter point of the standard with its index, IEC 61850 identifier,
function group (``purpose``), units, limits and mandatory flags.

Run from the ``interoperability_service`` directory (as a script, so a broken generated module
cannot stop regeneration)::

    python src/interoperability/models/ieee1815_2/generate_models.py [--source FILE] [--out DIR]

Outputs, all overwritten in place:

* ``points.py``            ``AI`` / ``AO`` / ``BI`` / ``BO`` / ``CTR`` IntEnums and the
  ``POINTS`` registry of :class:`~.common.PointDefinition`
* ``profiles.py``          one class per function group plus repeated equipment blocks
* ``profile_builders.py``  ``build_<group>(...)`` keyword-only constructors
* ``__init__.py``          package exports
"""
from __future__ import annotations

import argparse
import json
import keyword
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from pydantic import BaseModel

HERE = Path(__file__).resolve().parent
# The reconciled test-tool profile vendored in the repository (see sources/ieee1815_2/SOURCE.md).
DEFAULT_SOURCE = HERE.parents[3] / 'sources' / 'ieee1815_2' / 'full.json'

HEADER = '"""{title}\n\nGenerated by ``interoperability.models.ieee1815_2.generate_models``. Do not edit by hand.\n"""\n'

POINT_TYPES = ['AI', 'AO', 'BI', 'BO', 'CTR']
VALUE_ANNOTATION = {'AI': 'float | None', 'AO': 'float | None', 'BI': 'bool | None', 'BO': 'bool | None', 'CTR': 'int | None'}

#: Purpose labels in the source are not perfectly consistent; fold the variants together.
PURPOSE_ALIASES = {
    'Const VArs': 'Constant Vars',
    'Const Vars': 'Constant Vars',
    'Volt-VAr': 'Volt-Var',
    'Watt-VAr': 'Watt-Var',
    'Curves': 'Discovery',
    'Schedules': 'Discovery',
    'Functions': 'Discovery',
    'Meters': 'Discovery',
    'Inverters': 'Discovery',
    'Batteries': 'Discovery',
    'DER_Units': 'Discovery',
    'Number of Units': 'Discovery',
    'System Meter': 'Discovery',
    'Vendor': 'Discovery',
    'Experimental': 'Discovery',
    'Gap #1': 'Discovery',
    'Gap #2': 'Discovery',
    'SCADA, Config': 'Discovery',
}

#: Repeated equipment blocks: (source collection key, Key entry, class name)
EQUIPMENT_BLOCKS = [
    ('meters', 'meter', 'Meter'),
    ('ders', 'der', 'DERUnit'),
    ('inverters', 'inverter', 'Inverter'),
    ('batteries', 'battery', 'Battery'),
]
#: AI template blocks that describe the "selected" curve / schedule edit buffers, folded
#: into the AI side of the named function group.
TEMPLATE_BLOCKS = [('curves', 'Curve'), ('schedules_bc', 'BC Scheduling'), ('schedules', 'Scheduling')]

RESERVED = set(dir(BaseModel)) | set(keyword.kwlist) | {'POINT_TYPE', 'START', 'POINTS_PER', 'PURPOSE'}


# --------------------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------------------
def identifier(text: str) -> str:
    txt = re.sub(r'[^A-Za-z0-9_]+', '_', text).strip('_')
    txt = re.sub(r'_+', '_', txt)
    if not txt:
        txt = 'point'
    if txt[0].isdigit():
        txt = 'P' + txt
    if txt in RESERVED:
        txt += '_'
    return txt


def class_name(purpose: str) -> str:
    parts = re.split(r'[^A-Za-z0-9]+', purpose)
    txt = ''.join(p[:1].upper() + p[1:] for p in parts if p)
    return txt or 'Misc'


def snake_case(name: str) -> str:
    txt = re.sub(r'(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])', '_', name)
    return re.sub(r'_+', '_', txt).lower()


def unique(name: str, taken: set[str], suffix: str) -> str:
    if name not in taken:
        taken.add(name)
        return name
    candidate = f'{name}_{suffix}'
    n = 2
    while candidate in taken:
        candidate = f'{name}_{suffix}_{n}'
        n += 1
    taken.add(candidate)
    return candidate


ENUM_RE = re.compile(r'<\s*(\d+)\s*>\s*([^<\n]+)')


def enum_members(text: str) -> list[tuple[str, int, str]]:
    """Parse ``<0> Off  <1> On`` style enumerations out of a point description."""
    found = ENUM_RE.findall(text)
    if len(found) < 2:
        return []
    members: list[tuple[str, int, str]] = []
    taken: set[str] = set()
    for value, label in found:
        label = label.strip().rstrip('.,;')
        member = re.sub(r'[^A-Za-z0-9]+', '_', label).strip('_').upper()
        if not member or member[0].isdigit():
            member = 'V' + str(value) + ('_' + member if member else '')
        if member in taken:
            member = f'{member}_{value}'
        taken.add(member)
        members.append((member, int(value), label))
    return members


def first_sentence(text: str) -> str:
    txt = text.strip().split('\n')[0].strip()
    return txt


def literal(value: Any) -> str:
    return repr(value)


# --------------------------------------------------------------------------------------
# intermediate representation
# --------------------------------------------------------------------------------------
@dataclass
class FieldSpec:
    name: str
    annotation: str
    description: str
    extra: dict[str, Any]
    is_array: bool = False
    enum_name: str | None = None
    default: str = 'None'


@dataclass
class GroupSpec:
    name: str
    point_type: str
    fields: list[FieldSpec] = field(default_factory=list)
    start: int | None = None
    points_per: int | None = None


@dataclass
class ProfileSpec:
    name: str
    purpose: str
    groups: dict[str, GroupSpec] = field(default_factory=dict)
    start: int | None = None
    points_per: int | None = None
    is_equipment: bool = False


@dataclass
class EnumSpec:
    name: str
    members: list[tuple[str, int, str]]
    doc: str


class Generator:

    def __init__(self, data: dict[str, Any]):
        self.data = data
        self.key = data['Key']
        self.enums: list[EnumSpec] = []
        self.enum_names: set[str] = set()
        self.definitions: dict[str, dict[int, dict[str, Any]]] = {pt: {} for pt in POINT_TYPES}
        self.profiles: dict[str, ProfileSpec] = {}
        self.equipment: list[ProfileSpec] = []

    # ---- point definitions -----------------------------------------------------------
    def definition(self, pt: str, p: dict[str, Any], purpose: str) -> dict[str, Any]:
        d: dict[str, Any] = {
            'point_type': pt,
            'index': p['point_index'],
            'uid': p['iec_61850_uid'],
            'name': p['name'].strip(),
            'purpose': purpose,
        }
        if p.get('mandatory_1815'):
            d['mandatory_1815'] = True
        if p.get('mandatory_1547'):
            d['mandatory_1547'] = True
        for src, dst in (('event_class', 'event_class'), ('units', 'units'), ('minimum', 'minimum'), ('maximum', 'maximum'),
                         ('multiplier', 'multiplier'), ('offset', 'offset'), ('value', 'default'), ('state_0', 'state_0'),
                         ('state_1', 'state_1'), ('counter_event_class', 'counter_event_class'),
                         ('frozen_counter_exists', 'frozen_counter_exists'), ('frozen_counter_event_class', 'frozen_counter_event_class')):
            if p.get(src) is not None:
                d[dst] = p[src]
        for assoc in ('assoc_ai', 'assoc_ao', 'assoc_bi', 'assoc_bo'):
            if p.get(assoc):
                d['associated'] = p[assoc]
        return d

    def register(self, pt: str, p: dict[str, Any], purpose: str) -> None:
        idx = p['point_index']
        if idx not in self.definitions[pt]:
            self.definitions[pt][idx] = self.definition(pt, p, purpose)

    # ---- fields ----------------------------------------------------------------------
    def make_field(self, pt: str, p: dict[str, Any], name: str, *, index: int | None = None, offset: int | None = None) -> FieldSpec:
        extra: dict[str, Any] = {'point_type': pt, 'uid': p['iec_61850_uid']}
        if index is not None:
            extra['index'] = index
        if offset is not None:
            extra['offset'] = offset
        for k in ('units', 'event_class', 'minimum', 'maximum', 'multiplier', 'offset', 'state_0', 'state_1', 'mandatory_1815', 'mandatory_1547'):
            if k == 'offset':
                if p.get('offset') not in (None, 0.0):
                    extra['value_offset'] = p['offset']
                continue
            if p.get(k) not in (None, '', False):
                extra[k] = p[k]
        annotation = VALUE_ANNOTATION[pt]
        enum_name = None
        if pt in ('AI', 'AO') and (p.get('units') == 'Enum' or 'numeration' in p['name']):
            members = enum_members(p['name'])
            if members:
                enum_name = self.add_enum(name, p, members)
                annotation = f'{enum_name} | int | None'
        return FieldSpec(name=name, annotation=annotation, description=first_sentence(p['name']), extra=extra, enum_name=enum_name)

    def make_array_field(self, pt: str, items: list[dict[str, Any]], name: str, *, base: int | None = None) -> FieldSpec:
        first = items[0]
        extra: dict[str, Any] = {'point_type': pt, 'uid': re.sub(r'\.?1(\.|$)', r'.N\1', first['iec_61850_uid'], count=1)}
        if base is None:
            extra['indexes'] = [i['point_index'] for i in items]
        else:
            extra['offsets'] = [i['point_index'] - base for i in items]
        if first.get('units'):
            extra['units'] = first['units']
        desc = re.sub(r'\b1\b', 'N', first_sentence(first['name']), count=1)
        return FieldSpec(name=name, annotation=f'list[{VALUE_ANNOTATION[pt]}]', description=f'{desc} (one entry per point)', extra=extra, is_array=True, default='Field(default_factory=list)')

    def add_enum(self, field_name: str, p: dict[str, Any], members: list[tuple[str, int, str]]) -> str:
        # Enumerations are shared by uid so paired AI/AO points use one class.
        base = re.sub(r'^(Meter|Inverter|Battery|DER_Unit)\d+\.', '', p['iec_61850_uid'])
        name = 'Enum_' + identifier(base)
        if name in self.enum_names:
            return name
        self.enum_names.add(name)
        self.enums.append(EnumSpec(name=name, members=members, doc=f'Enumeration for ``{base}`` ({first_sentence(p["name"])})'))
        return name

    # ---- profiles --------------------------------------------------------------------
    def profile(self, purpose: str) -> ProfileSpec:
        purpose = PURPOSE_ALIASES.get(purpose, purpose)
        if purpose not in self.profiles:
            self.profiles[purpose] = ProfileSpec(name=class_name(purpose), purpose=purpose)
        return self.profiles[purpose]

    def group(self, prof: ProfileSpec, pt: str) -> GroupSpec:
        if pt not in prof.groups:
            prof.groups[pt] = GroupSpec(name=f'{prof.name}{pt}', point_type=pt, start=prof.start, points_per=prof.points_per)
        return prof.groups[pt]

    def build(self) -> None:
        taken_by_group: dict[str, set[str]] = {}
        for pt in POINT_TYPES:
            section = self.data[pt]
            points = section['points'] if isinstance(section, dict) else section
            for p in points:
                purpose = PURPOSE_ALIASES.get(p.get('purpose') or 'Misc', p.get('purpose') or 'Misc')
                self.register(pt, p, purpose)
                if pt == 'CTR' and p['point_index'] >= self.key['meter']['ctr']['start']:
                    continue    # instance points of the meter block; handled as a template below
                prof = self.profile(purpose)
                grp = self.group(prof, pt)
                taken = taken_by_group.setdefault(grp.name, set())
                name = unique(identifier(p['iec_61850_uid']), taken, str(p['point_index']))
                grp.fields.append(self.make_field(pt, p, name, index=p['point_index']))
        # Selected-curve / selected-schedule AI edit buffers.
        for collection, purpose in TEMPLATE_BLOCKS:
            template = self.data['AI'][collection][0]
            prof = self.profile(purpose)
            grp = self.group(prof, 'AI')
            taken = taken_by_group.setdefault(grp.name, set())
            for key, value in template.items():
                if isinstance(value, list):
                    for item in value:
                        self.register('AI', item, purpose)
                    grp.fields.append(self.make_array_field('AI', value, unique(key, taken, 'arr')))
                else:
                    self.register('AI', value, purpose)
                    grp.fields.append(self.make_field('AI', value, unique(key, taken, str(value['point_index'])), index=value['point_index']))
        # Repeated equipment blocks.
        for collection, key_name, cls in EQUIPMENT_BLOCKS:
            prof = ProfileSpec(name=cls, purpose=f'{cls} equipment block', is_equipment=True)
            for pt in POINT_TYPES:
                cfg = self.key[key_name][pt.lower()]
                if not cfg.get('points_per'):
                    continue
                start, per = cfg['start'], cfg['points_per']
                if pt == 'CTR':
                    items = [p for p in self.data['CTR'] if start <= p['point_index'] < start + per]
                    template = {identifier(p['iec_61850_uid'].split('.', 1)[-1]).lower(): p for p in items}
                else:
                    template = self.data[pt][collection][0]
                grp = GroupSpec(name=f'{cls}{pt}', point_type=pt, start=start, points_per=per)
                taken: set[str] = set()
                for key, value in template.items():
                    if isinstance(value, list):
                        grp.fields.append(self.make_array_field(pt, value, unique(identifier(key), taken, 'arr'), base=start))
                        for item in value:
                            self.register(pt, item, 'Equipment Data')
                    else:
                        self.register(pt, value, 'Equipment Data')
                        grp.fields.append(self.make_field(pt, value, unique(identifier(key), taken, str(value['point_index'])), offset=value['point_index'] - start))
                if grp.fields:
                    prof.groups[pt] = grp
            self.equipment.append(prof)

    # ---- rendering -------------------------------------------------------------------
    def render_points(self) -> str:
        lines = [HEADER.format(title='IEEE 1815.2 point indexes and point definitions.')]
        lines.append('from __future__ import annotations\n')
        lines.append('import enum\n')
        lines.append('from .common import PointDefinition, PointType\n')
        lines.append("__all__ = ['AI', 'AO', 'BI', 'BO', 'CTR', 'POINTS', 'definition', 'find']\n")
        for pt in POINT_TYPES:
            lines.append(f'\nclass {pt}(enum.IntEnum):')
            lines.append(f'    """IEEE 1815.2 {pt} point indexes, named by IEC 61850 identifier."""\n')
            taken: set[str] = set()
            for idx in sorted(self.definitions[pt]):
                d = self.definitions[pt][idx]
                name = unique(identifier(d['uid']), taken, str(idx))
                lines.append(f'    {name} = {idx}')
            lines.append('')
        lines.append('\nPOINTS: dict[PointType, dict[int, PointDefinition]] = {')
        for pt in POINT_TYPES:
            lines.append(f'    PointType.{pt}: {{')
            for idx in sorted(self.definitions[pt]):
                d = dict(self.definitions[pt][idx])
                d.pop('point_type')
                args = ', '.join(f'{k}={literal(v)}' for k, v in d.items())
                lines.append(f'        {idx}: PointDefinition(point_type=PointType.{pt}, {args}),')
            lines.append('    },')
        lines.append('}\n')
        lines.append('''
def definition(point_type: PointType | str, index: int) -> PointDefinition:
    """Return the :class:`PointDefinition` for ``point_type`` / ``index``."""
    return POINTS[PointType(point_type)][int(index)]


def find(uid: str, point_type: PointType | str | None = None) -> list[PointDefinition]:
    """Return every point whose IEC 61850 identifier equals ``uid``."""
    types = [PointType(point_type)] if point_type is not None else list(PointType)
    return [d for pt in types for d in POINTS[pt].values() if d.uid == uid]
''')
        return '\n'.join(lines)

    @staticmethod
    def render_field(f: FieldSpec) -> str:
        args = []
        if f.default.startswith('Field('):
            args.append(f.default[len('Field('):-1])
        else:
            args.append(f'default={f.default}')
        args.append(f'description={literal(f.description)}')
        if f.enum_name:
            args.append("union_mode='left_to_right'")
        args.append(f'json_schema_extra={literal(f.extra)}')
        return f'    {f.name}: {f.annotation} = Field({", ".join(args)})'

    def render_group(self, grp: GroupSpec, prof: ProfileSpec) -> list[str]:
        lines = [f'\nclass {grp.name}(PointGroup):']
        lines.append(f'    """{grp.point_type} points of the {prof.purpose!r} group."""\n')
        lines.append(f'    POINT_TYPE: ClassVar[PointType] = PointType.{grp.point_type}')
        if grp.start is not None:
            lines.append(f'    START: ClassVar[int | None] = {grp.start}')
            lines.append(f'    POINTS_PER: ClassVar[int | None] = {grp.points_per}')
        lines.append('')
        for f in grp.fields:
            lines.append(self.render_field(f))
        lines.append('')
        return lines

    def render_profiles(self) -> str:
        lines = [HEADER.format(title='IEEE 1815.2 function groups as pydantic models.')]
        lines.append('from __future__ import annotations\n')
        lines.append('import enum')
        lines.append('from typing import ClassVar\n')
        lines.append('from pydantic import Field\n')
        lines.append('from .common import PointGroup, PointType, Profile\n')
        names = [e.name for e in self.enums]
        for prof in list(self.profiles.values()) + self.equipment:
            names.append(prof.name)
            names.extend(g.name for g in prof.groups.values())
        lines.append('__all__ = [')
        for n in sorted(names):
            lines.append(f'    {literal(n)},')
        lines.append(']\n')
        for e in self.enums:
            lines.append(f'\nclass {e.name}(enum.IntEnum):')
            lines.append(f'    """{e.doc}"""')
            for member, value, label in e.members:
                lines.append(f'    {member} = {value}    # {label}')
            lines.append('')
        for prof in sorted(self.profiles.values(), key=lambda p: p.name) + self.equipment:
            for pt in POINT_TYPES:
                if pt in prof.groups:
                    lines.extend(self.render_group(prof.groups[pt], prof))
            lines.append(f'\nclass {prof.name}(Profile):')
            what = 'Repeated equipment block' if prof.is_equipment else 'Function group'
            lines.append(f'    """{what} {prof.purpose!r} of the IEEE 1815.2 point list."""\n')
            lines.append(f'    PURPOSE: ClassVar[str] = {literal(prof.purpose)}')
            if prof.is_equipment:
                any_group = next(iter(prof.groups.values()))
                lines.append(f'    START: ClassVar[int | None] = {any_group.start}')
                lines.append(f'    POINTS_PER: ClassVar[int | None] = {any_group.points_per}')
            lines.append('')
            for pt in POINT_TYPES:
                if pt in prof.groups:
                    lines.append(f'    {pt}: {prof.groups[pt].name} | None = Field(default=None, description={literal(f"{pt} points")})')
            lines.append('')
        return '\n'.join(lines).rstrip() + '\n'

    def render_builders(self) -> str:
        lines = [HEADER.format(title='Keyword-only constructors for IEEE 1815.2 function groups and point databases.')]
        lines.append('from __future__ import annotations\n')
        lines.append('from typing import Any\n')
        lines.append('from .common import PointDatabase, Profile')
        lines.append('from .profiles import *  # noqa: F401,F403\n')
        names = ['build_point_database']
        lines.append('''
def build_point_database(*profiles: Profile | tuple[Profile, int], AI: dict[int | str, Any] | None = None, AO: dict[int | str, Any] | None = None, BI: dict[int | str, Any] | None = None, BO: dict[int | str, Any] | None = None, CTR: dict[int | str, Any] | None = None) -> PointDatabase:
    """Assemble a :class:`PointDatabase` from profiles and/or raw ``{index: value}`` tables.

    Profiles are written in order, later ones overriding earlier ones. A repeated equipment
    block is passed as ``(profile, instance_number)``. Raw tables are applied last.
    """
    db = PointDatabase()
    for item in profiles:
        profile, instance = (item if isinstance(item, tuple) else (item, None))
        profile.to_points(instance, db)
    raw = PointDatabase.model_validate({'AI': AI or {}, 'AO': AO or {}, 'BI': BI or {}, 'BO': BO or {}, 'CTR': CTR or {}})
    return db.merge(raw)
''')
        for prof in sorted(self.profiles.values(), key=lambda p: p.name) + self.equipment:
            snake = snake_case(prof.name)
            for pt in POINT_TYPES:
                grp = prof.groups.get(pt)
                if grp is None:
                    continue
                fname = f'build_{snake}_{pt.lower()}'
                names.append(fname)
                lines.append(f'\ndef {fname}(')
                lines.append('    *,')
                for f in grp.fields:
                    lines.append(f'    {f.name}: {f.annotation} = None,')
                lines.append(f') -> {grp.name}:')
                lines.append(f'    """Build the {pt} points of the {prof.purpose!r} group."""')
                lines.append(f'    return {grp.name}(')
                for f in grp.fields:
                    if f.is_array:
                        lines.append(f'        {f.name}={f.name} if {f.name} is not None else [],')
                    else:
                        lines.append(f'        {f.name}={f.name},')
                lines.append('    )\n')
            fname = f'build_{snake}'
            names.append(fname)
            lines.append(f'\ndef {fname}(')
            lines.append('    *,')
            for pt in POINT_TYPES:
                if pt in prof.groups:
                    lines.append(f'    {pt}: {prof.groups[pt].name} | dict[str, Any] | None = None,')
            lines.append(f') -> {prof.name}:')
            lines.append(f'    """Build the {prof.purpose!r} group from its per-type point groups."""')
            lines.append(f'    return {prof.name}(')
            for pt in POINT_TYPES:
                if pt in prof.groups:
                    lines.append(f'        {pt}={pt},')
            lines.append('    )\n')
        lines.append('\n__all__ = [')
        for n in names:
            lines.append(f'    {literal(n)},')
        lines.append(']')
        return '\n'.join(lines) + '\n'

