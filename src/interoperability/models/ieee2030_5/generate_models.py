@dataclass
class EditionSpec:
    edition: str
    namespace: str
    types: dict[str, tuple[str | None, list[str]]]      # type name -> (base type, own element/attribute names)
    simple_types: list[str]
    curve_types: list[tuple[int, str]]
    control_modes: dict[str, list[tuple[int, str]]]     # DERControlType / DERControlType2 bit positions


def parse_edition(edition: str, schema: Path) -> EditionSpec:
    """Read one ``sep.xsd``: every named type with its base and own members, plus the curve types and control-mode
    bits the schema documents in prose (``11 - opModVoltVar``, ``0 = opModMaxLimPctVAAbsorb``)."""
    root = ET.parse(schema).getroot()
    types: dict[str, tuple[str | None, list[str]]] = {}
    doc_of: dict[str, str] = {}
    for ct in root.findall(f'{XS}complexType'):
        members = [e.get('name') for e in ct.iter(f'{XS}element') if e.get('name')]
        members += ['@' + a.get('name') for a in ct.iter(f'{XS}attribute') if a.get('name')]
        ext = ct.find(f'.//{XS}extension')
        types[ct.get('name')] = (ext.get('base') if ext is not None else None, members)
        doc = ct.find(f'{XS}annotation/{XS}documentation')
        doc_of[ct.get('name')] = (doc.text or '') if doc is not None else ''
    simple = [st.get('name') for st in root.findall(f'{XS}simpleType')]
    for st in root.findall(f'{XS}simpleType'):
        doc = st.find(f'{XS}annotation/{XS}documentation')
        doc_of[st.get('name')] = (doc.text or '') if doc is not None else ''

    def listed(text: str, sep: str) -> list[tuple[int, str]]:
        return [(int(n), name) for n, name in re.findall(rf'^\s*(\d+)\s*{sep}\s*(opMod\w+)', text, re.M)]

    return EditionSpec(edition=edition, namespace=root.get('targetNamespace', ''), types=types, simple_types=simple,
                       curve_types=listed(doc_of.get('DERCurveType', ''), '-'),
                       control_modes={name: listed(doc_of.get(name, ''), '[-=]')
                                      for name in ('DERControlType', 'DERControlType2') if name in doc_of})


EDITION_CLASS = '''
@dataclass(frozen=True)
class Edition:
    """One edition of the schema: its XML namespace, every named type with its base type and own element and
    attribute names (attributes prefixed ``@``), its simple types, the curve types ``DERCurveType`` documents and
    the control-mode bit positions of ``DERControlType`` (and ``DERControlType2`` from 2023)."""
    edition: str
    namespace: str
    types: dict[str, tuple[str | None, frozenset[str]]]
    simple_types: frozenset[str]
    curve_types: tuple[tuple[int, str], ...]
    control_modes: dict[str, tuple[tuple[int, str], ...]]

    def fields_of(self, type_name: str) -> frozenset[str]:
        """Every element and attribute of ``type_name`` in this edition, inherited ones included."""
        names: set[str] = set()
        seen: set[str] = set()
        while type_name and type_name in self.types and type_name not in seen:
            seen.add(type_name)
            base, own = self.types[type_name]
            names |= own
            type_name = base
        return frozenset(names)

    def defines(self, type_name: str) -> bool:
        return type_name in self.types or type_name in self.simple_types

'''

EDITION_HELPERS = '''
def fields_of(edition: str, type_name: str) -> frozenset[str]:
    """Elements and attributes of ``type_name`` in ``edition`` (empty when the edition lacks the type)."""
    return EDITIONS[edition].fields_of(type_name)


def available_in(edition: str, type_name: str, field_name: str) -> bool:
    """Whether ``edition`` defines ``field_name`` on ``type_name`` (attributes as ``@name``)."""
    return field_name in EDITIONS[edition].fields_of(type_name)
'''


def render_editions(specs: list[EditionSpec], source_note: str) -> str:
    lines = [HEADER.format(title='What each IEEE 2030.5 edition defines.', source=source_note)]
    lines.append('from __future__ import annotations\n')
    lines.append('from dataclasses import dataclass\n')
    lines.append(f'LATEST_EDITION = {LATEST_EDITION!r}\n')
    lines.append(EDITION_CLASS)
    lines.append('EDITIONS: dict[str, Edition] = {')
    for spec in sorted(specs, key=lambda s: s.edition):
        lines.append(f'    {spec.edition!r}: Edition(')
        lines.append(f'        edition={spec.edition!r},')
        lines.append(f'        namespace={spec.namespace!r},')
        lines.append('        types={')
        for name in sorted(spec.types):
            base, members = spec.types[name]
            lines.append(f'            {name!r}: ({base!r}, frozenset({sorted(members)!r})),')
        lines.append('        },')
        lines.append(f'        simple_types=frozenset({sorted(spec.simple_types)!r}),')
        lines.append(f'        curve_types={tuple(spec.curve_types)!r},')
        modes = ', '.join(f'{k!r}: {tuple(v)!r}' for k, v in spec.control_modes.items())
        lines.append('        control_modes={' + modes + '},')
        lines.append('    ),')
    lines.append('}\n')
    lines.append(EDITION_HELPERS)
    return '\n'.join(lines) + '\n'


def generate(sep_module: Path, out: Path, enums_dir: Path, source_note: str,
             editions: dict[str, Path] | None = None) -> Generator:
    fetch_sources(enums_dir)
    gen = Generator(sep_module, enums_dir, source_note)
    gen.parse()
    (out / 'sep.py').write_text(gen.render_sep(), encoding='utf-8')
    (out / 'enums.py').write_text(gen.render_enums(), encoding='utf-8')
    (out / 'profile_builders.py').write_text(gen.render_builders(), encoding='utf-8')
    if editions:
        specs = [parse_edition(edition, path) for edition, path in sorted(editions.items())]
        (out / 'editions.py').write_text(render_editions(specs, source_note), encoding='utf-8')
    (out / '__init__.py').write_text(gen.render_init(), encoding='utf-8')
    return gen


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--schema', type=Path, default=None,
                        help='sep.xsd to render with xsdata (default: the newest edition under 1547_standards/2030.5)')
    parser.add_argument('--source-dir', type=Path, default=None,
                        help='directory holding a pre-rendered xsdata sep.py instead of --schema')
    parser.add_argument('--editions', nargs='*', default=None, metavar='EDITION=PATH',
                        help='sep.xsd per edition for editions.py (default: every edition found under 1547_standards/2030.5)')
    parser.add_argument('--enums-dir', type=Path, default=SOURCES_DIR,
                        help='directory holding the VOLTTRON enums.py and constants.py')
    parser.add_argument('--out', type=Path, default=HERE, help='package directory to write into')
    args = parser.parse_args(argv)

    discovered = discover_schemas()
    if args.editions is None:
        editions = discovered
    else:
        editions = {}
        for item in args.editions:
            edition, _, path = item.partition('=')
            editions[edition] = Path(path)
    if args.source_dir is not None:
        sep_module = args.source_dir / 'sep.py'
        note = f'a pre-rendered xsdata module ({sep_module.name})'
    else:
        schema = args.schema
        if schema is None:
            if not discovered:
                raise SystemExit(f'No sep.xsd found under {STANDARDS_DIR}; pass --schema or --source-dir.')
            edition = max(discovered)
            schema = discovered[edition]
        else:
            edition = next((e for e, p in editions.items() if p.resolve() == schema.resolve()), None)
        sep_module = run_xsdata(schema, Path(tempfile.mkdtemp(prefix='ieee2030_5_xsdata_')))
        note = schema_note(schema, edition)
    gen = generate(sep_module, args.out, args.enums_dir, note, editions)
    n_builders = sum(1 for s in gen.classes.values() if gen.wants_builder(s))
    suffix = (', editions ' + ', '.join(sorted(editions)) if editions else '') + f', {len(gen.folded_wrappers)} simple-content wrappers folded'
    print(f'Generated {len(gen.classes)} IEEE 2030.5 types, {len(gen.enums)} enums, {n_builders} builders{suffix} into {args.out}')


if __name__ == '__main__':
    main()
