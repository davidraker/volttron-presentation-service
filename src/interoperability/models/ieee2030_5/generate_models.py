def fetch_sources(source_dir: Path) -> None:
    """Make sure the VOLTTRON ``enums.py`` and ``constants.py`` exist in ``source_dir`` (downloaded from the pinned
    commit when the vendored copies are not used)."""
    source_dir.mkdir(parents=True, exist_ok=True)
    for filename in ('enums.py', 'constants.py'):
        target = source_dir / filename
        if target.exists():
            continue
        url = BASE_URL + filename
        print(f'Downloading {url}')
        with urllib.request.urlopen(url, timeout=60) as resp:
            target.write_bytes(resp.read())


def discover_schemas(root: Path = STANDARDS_DIR) -> dict[str, Path]:
    """``{edition: sep.xsd}`` for every edition folder (``2013``, ``2018``, ``2023``) under the standards share."""
    found: dict[str, Path] = {}
    if not root.is_dir():
        return found
    for path in sorted(root.glob('*/**/sep.xsd')):
        if '__MACOSX' in path.parts:
            continue
        edition = path.relative_to(root).parts[0]
        if re.fullmatch(r'20\d\d', edition):
            found.setdefault(edition, path)
    return found


def schema_note(schema: Path, edition: str | None) -> str:
    digest = hashlib.sha256(schema.read_bytes()).hexdigest()[:12]
    label = f'the IEEE 2030.5-{edition} ' if edition else 'the IEEE 2030.5 '
    return (f'{label}``sep.xsd`` schema ({schema.name}, sha256 {digest}) via xsdata, with enumerations from the '
            f'Eclipse VOLTTRON ``enums.py``/``constants.py`` (commit {COMMIT[:12]})')


def run_xsdata(schema: Path, out_dir: Path) -> Path:
    """Render ``schema`` to xsdata dataclasses in ``out_dir`` and return the module written."""
    out_dir.mkdir(parents=True, exist_ok=True)
    config = out_dir / '.xsdata.xml'
    config.write_text(XSDATA_CONFIG, encoding='utf-8')
    try:
        import xsdata  # noqa: F401
    except ImportError:
        raise SystemExit('Rendering the schema needs xsdata: pip install "xsdata[cli]"')
    result = subprocess.run([sys.executable, '-m', 'xsdata', 'generate', str(schema), '--config', str(config)],
                            cwd=out_dir, capture_output=True, text=True)
    candidates = sorted((p for p in out_dir.rglob('*.py') if p.name != '__init__.py'),
                        key=lambda p: p.stat().st_size, reverse=True)
    if not candidates:
        raise SystemExit(f'xsdata produced no module in {out_dir}:\n{result.stdout}\n{result.stderr}')
    if result.returncode:
        # xsdata tries to run ruff on its output; a missing formatter is not a failure of the rendering.
        tail = result.stderr.strip().splitlines()[-1] if result.stderr.strip() else ''
        print(f'xsdata exited {result.returncode} (output kept): {tail}')
    return candidates[0]


IVAR_RE = re.compile(r':ivar\s+(\w+):[ \t]*(.*?)(?=\n\s*:ivar|\Z)', re.S)


def split_docstring(doc: str | None) -> tuple[str, dict[str, str]]:
    if not doc:
        return '', {}
    head = doc.split(':ivar', 1)[0]
    description = ' '.join(line.strip() for line in head.strip().splitlines()).strip()
    ivars = {name: ' '.join(text.split()) for name, text in IVAR_RE.findall(doc)}
    return description, ivars


def convert_annotation(node: ast.expr) -> tuple[str, bool, bool]:
    """Return (pydantic annotation, is_list, is_hex_binary) for an xsdata annotation."""
    txt = ast.unparse(node)
    is_list = False
    hex_binary = False
    m = re.fullmatch(r'Optional\[(.+)\]', txt)
    if m:
        txt = m.group(1)
    m = re.fullmatch(r'[Ll]ist\[(.+)\]', txt)
    if m:
        is_list = True
        txt = m.group(1)
    if txt == 'object':
        txt = 'Any'
    if txt == 'bytes':
        txt = 'str'
        hex_binary = True
    if is_list:
        return f'list[{txt}]', True, hex_binary
    return f'{txt} | None', False, hex_binary


def docstring(text: str) -> str:
    """A triple-quoted literal of ``text``, safe for schema documentation that contains quotes or backslashes."""
    text = text.replace('\\', '\\\\').replace('"""', '\\"\\"\\"')
    if text.endswith('"'):
        text += ' '
    return f'"""{text}"""'


class Generator:

    def __init__(self, sep_module: Path, enums_dir: Path, source_note: str):
        self.sep_module = sep_module
        self.enums_dir = enums_dir
        self.source_note = source_note
        self.classes: dict[str, ClassSpec] = {}
        self.enums: list[EnumSpec] = []
        self.folded_wrappers: list[str] = []

    # ---- parsing ---------------------------------------------------------------------
    def parse(self) -> None:
        tree = ast.parse(self.sep_module.read_text(encoding='utf-8'))
        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                self.classes[node.name] = self.parse_class(node)
        for filename in ('enums.py', 'constants.py'):
            path = self.enums_dir / filename
            if path.exists():
                self.parse_enums(ast.parse(path.read_text(encoding='utf-8')))
        self.fold_schema_quirks()

    def parse_class(self, node: ast.ClassDef) -> ClassSpec:
        description, ivars = split_docstring(ast.get_docstring(node))
        xml_name = None
        spec = ClassSpec(name=node.name, bases=[ast.unparse(b) for b in node.bases], doc=description, xml_name=None)
        for stmt in node.body:
            if isinstance(stmt, ast.ClassDef) and stmt.name == 'Meta':
                for s in stmt.body:
                    if isinstance(s, ast.Assign) and ast.unparse(s.targets[0]) == 'name':
                        xml_name = ast.literal_eval(s.value)
            elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                spec.fields.append(self.parse_field(stmt, ivars))
        spec.xml_name = xml_name if xml_name and xml_name != node.name else None
        return spec

    def parse_field(self, stmt: ast.AnnAssign, ivars: dict[str, str]) -> FieldSpec:
        name = stmt.target.id  # type: ignore[union-attr]
        metadata: dict[str, Any] = {}
        if isinstance(stmt.value, ast.Call):
            for kw in stmt.value.keywords:
                if kw.arg == 'metadata':
                    metadata = ast.literal_eval(kw.value)
        # xsdata gives Python-unfriendly schema names a safe alias (``type`` -> ``type_value``); the models use the
        # schema's name, as the earlier source did.
        wire = metadata.get('name')
        if isinstance(wire, str) and wire != name and wire.isidentifier() and wire not in RESERVED:
            name = wire
        if name in RESERVED:
            raise ValueError(f'Field name {name!r} clashes with pydantic or Python reserved names')
        annotation, is_list, hex_binary = convert_annotation(stmt.annotation)
        extra: dict[str, Any] = {'xml': 'attribute' if metadata.get('type') == 'Attribute' else 'element'}
        if metadata.get('type') in ('Wildcard', 'Attributes'):
            extra['xml'] = 'any'
        if metadata.get('required'):
            extra['required'] = True
        if REVISION_MARKER.search(name):
            extra['revision_marker'] = True
        if hex_binary:
            extra['format'] = 'base16'
        constraints: dict[str, Any] = {}
        for key in ('max_length', 'min_occurs', 'max_occurs', 'min_inclusive', 'max_inclusive'):
            if key in metadata:
                extra[key] = metadata[key]
        if not hex_binary and not is_list and 'max_length' in metadata and annotation.startswith('str'):
            constraints['max_length'] = metadata['max_length']
        if 'min_inclusive' in metadata and annotation.startswith('int'):
            constraints['ge'] = metadata['min_inclusive']
        if 'max_inclusive' in metadata and annotation.startswith('int'):
            constraints['le'] = metadata['max_inclusive']
        inner = annotation[len('list['):-1] if is_list else annotation[:-len(' | None')]
        if is_list:
            builder_annotation = f'list[{inner} | dict[str, Any]] | None' if inner[0].isupper() else f'list[{inner}] | None'
        else:
            builder_annotation = f'{inner} | dict[str, Any] | None' if inner[0].isupper() else annotation
        return FieldSpec(
            name=name,
            annotation=annotation,
            default='Field(default_factory=list)' if is_list else 'None',
            description=ivars.get(name, ''),
            extra=extra,
            constraints=constraints,
            builder_annotation=builder_annotation,
        )

    def parse_enums(self, tree: ast.Module) -> None:
        for node in tree.body:
            if not isinstance(node, ast.ClassDef):
                continue
            members: list[tuple[str, int]] = []
            for stmt in node.body:
                if isinstance(stmt, ast.Assign) and isinstance(stmt.value, ast.Constant) and isinstance(stmt.value.value, int):
                    members.append((stmt.targets[0].id, stmt.value.value))  # type: ignore[attr-defined]
            if members:
                self.enums.append(EnumSpec(name=node.name, members=members, doc=f'IEEE 2030.5 ``{node.name}`` values.'))

    # ---- schema quirks -----------------------------------------------------------------
    def _rename_type(self, old: str, new: str) -> None:
        pattern = re.compile(rf'\b{re.escape(old)}\b')
        for spec in self.classes.values():
            spec.bases = [pattern.sub(new, b) for b in spec.bases]
            for f in spec.fields:
                if pattern.search(f.annotation):
                    self._retype(f, pattern.sub(new, f.annotation))

    @staticmethod
    def _retype(f: FieldSpec, annotation: str) -> None:
        f.annotation = annotation
        is_list = annotation.startswith('list[')
        inner = annotation[len('list['):-1] if is_list else annotation[:-len(' | None')]
        if is_list:
            f.builder_annotation = f'list[{inner} | dict[str, Any]] | None' if inner[0].isupper() else f'list[{inner}] | None'
        else:
            f.builder_annotation = f'{inner} | dict[str, Any] | None' if inner[0].isupper() else annotation

    def fold_schema_quirks(self) -> None:
        """Undo two renderings of the 2023 schema that are not model structure.

        1. Every root element is declared as an anonymous extension of its type adding the ``schemaVer`` attribute,
           which xsdata renders as ``X_1`` (the type) plus ``X(X_1)`` (the element). The type keeps its name and
           gains ``schemaVer`` as an optional attribute.
        2. Simple-content types (``PerCent``, ``PowerOfTenMultiplierType``, the ``*ControlType`` wrappers with their
           ``disabled`` attribute, the enumeration carriers such as ``DERType``) are a text value plus optional XML
           attributes. On the wire and in the service's dict convention they are the scalar, so fields of those types
           take the scalar annotation and record the wrapper and its attributes in their metadata; the wrapper classes
           are not emitted. Fields named after the schema (``type``) keep the schema's name, not xsdata's safe name.
        """
        for name, spec in list(self.classes.items()):
            wrapped = f'{name}_1'
            if spec.bases == [wrapped] and {f.name for f in spec.fields} <= {'schemaVer'} and wrapped in self.classes:
                typ = self.classes.pop(wrapped)
                typ.name = name
                typ.fields.extend(spec.fields)
                if typ.xml_name == name:
                    typ.xml_name = None
                self.classes[name] = typ
                self._rename_type(wrapped, name)

        def is_wrapper(spec: ClassSpec) -> bool:
            fields = self.all_fields(spec)
            return any(f.name == 'value' for f in fields) and \
                all(f.name == 'value' or f.extra.get('xml') in ('attribute', 'any') for f in fields)

        wrappers = {name: spec for name, spec in self.classes.items() if is_wrapper(spec)}

        def scalar_of(name: str, seen: frozenset = frozenset()) -> tuple[str, dict]:
            value = next(f for f in self.all_fields(wrappers[name]) if f.name == 'value')
            inner = value.annotation[:-len(' | None')]
            if inner in wrappers and inner not in seen:
                return scalar_of(inner, seen | {name})
            return inner, {k: v for k, v in value.extra.items() if k == 'format'}

        for spec in self.classes.values():
            if spec.name in wrappers:
                continue
            for f in spec.fields:
                is_list = f.annotation.startswith('list[')
                inner = f.annotation[len('list['):-1] if is_list else f.annotation[:-len(' | None')]
                if inner in wrappers:
                    scalar, extra = scalar_of(inner)
                    attributes = sorted(x.name for x in self.all_fields(wrappers[inner]) if x.extra.get('xml') == 'attribute')
                    f.extra.update(extra)
                    f.extra['wrapper'] = inner
                    if attributes:
                        f.extra['attributes'] = attributes
                    self._retype(f, f'list[{scalar}]' if is_list else f'{scalar} | None')
        for name in wrappers:
            del self.classes[name]
        self.folded_wrappers = sorted(wrappers)

    # ---- ordering --------------------------------------------------------------------
    def ordered(self) -> list[ClassSpec]:
        done: set[str] = set()
        out: list[ClassSpec] = []

        def visit(name: str) -> None:
            if name in done or name not in self.classes:
                return
            for base in self.classes[name].bases:
                visit(base)
            done.add(name)
            out.append(self.classes[name])

        for name in self.classes:
            visit(name)
        return out

    def all_fields(self, spec: ClassSpec) -> list[FieldSpec]:
        seen: dict[str, FieldSpec] = {}
        for base in spec.bases:
            if base in self.classes:
                for f in self.all_fields(self.classes[base]):
                    seen[f.name] = f
        for f in spec.fields:
            seen[f.name] = f
        return list(seen.values())

    def is_subclass(self, spec: ClassSpec, ancestor: str) -> bool:
        if spec.name == ancestor:
            return True
        return any(base in self.classes and self.is_subclass(self.classes[base], ancestor) for base in spec.bases)

    def wants_builder(self, spec: ClassSpec) -> bool:
        if spec.name.endswith(NO_BUILDER_SUFFIXES):
            return False
        if self.is_subclass(spec, 'List_type') or self.is_subclass(spec, 'List'):
            return False
        return True

    # ---- rendering -------------------------------------------------------------------
    @staticmethod
    def render_field(f: FieldSpec) -> str:
        args = []
        if f.default.startswith('Field('):
            args.append(f.default[len('Field('):-1])
        else:
            args.append(f'default={f.default}')
        if f.description:
            args.append(f'description={f.description!r}')
        for k, v in f.constraints.items():
            args.append(f'{k}={v!r}')
        args.append(f'json_schema_extra={f.extra!r}')
        return f'    {f.name}: {f.annotation} = Field({", ".join(args)})'

    def shadow_safe(self, f: FieldSpec, own_names: set[str]) -> FieldSpec:
        """Point at ``_T_<Type>`` aliases when a field name shadows a type used in the same class.

        With ``from __future__ import annotations`` pydantic resolves annotations in the class
        namespace, where ``EnvironmentalCost: list[EnvironmentalCost]`` would find the field
        instead of the class. Module-level aliases emitted after all classes avoid that.
        """
        def repl(m: re.Match[str]) -> str:
            return f'_T_{m.group(0)}' if m.group(0) in own_names and m.group(0) in self.classes else m.group(0)
        annotation = re.sub(r'\b[A-Za-z_]\w*\b', repl, f.annotation)
        if annotation == f.annotation:
            return f
        return FieldSpec(**{**f.__dict__, 'annotation': annotation})

    def render_sep(self) -> str:
        specs = self.ordered()
        lines = [HEADER.format(title='IEEE 2030.5 schema types as pydantic models.', source=self.source_note)]
        lines.append('from __future__ import annotations\n')
        lines.append('from typing import Any, ClassVar\n')
        lines.append('from pydantic import Field\n')
        lines.append('from .common import SepBase\n')
        lines.append('__all__ = [')
        for s in sorted(specs, key=lambda s: s.name):
            lines.append(f'    {s.name!r},')
        lines.append(']\n')
        for spec in specs:
            bases = ', '.join(spec.bases) if spec.bases else 'SepBase'
            lines.append(f'\nclass {spec.name}({bases}):')
            doc = spec.doc or f'IEEE 2030.5 {spec.name}.'
            lines.append('    ' + docstring(doc))
            body: list[str] = []
            if spec.xml_name:
                body.append(f'    XML_NAME: ClassVar[str | None] = {spec.xml_name!r}')
            own_names = {f.name for f in spec.fields}
            for f in spec.fields:
                body.append(self.render_field(self.shadow_safe(f, own_names)))
            if body:
                lines.append('')
                lines.extend(body)
            lines.append('')
        lines.append('\n# Aliases used where a field name shadows the type of the same name (see shadow_safe).')
        for s in specs:
            lines.append(f'_T_{s.name} = {s.name}')
        lines.append('\nfor _cls in list(globals().values()):')
        lines.append('    if isinstance(_cls, type) and issubclass(_cls, SepBase) and _cls is not SepBase:')
        lines.append('        _cls.model_rebuild()')
        lines.append('del _cls')
        return '\n'.join(lines) + '\n'

    def render_enums(self) -> str:
        lines = [HEADER.format(title='IEEE 2030.5 enumerations.', source=self.source_note)]
        lines.append('from __future__ import annotations\n')
        lines.append('import enum\n')
        lines.append('__all__ = [')
        for e in sorted(self.enums, key=lambda e: e.name):
            lines.append(f'    {e.name!r},')
        lines.append(']\n')
        for e in self.enums:
            lines.append(f'\nclass {e.name}(enum.IntEnum):')
            lines.append('    ' + docstring(e.doc))
            for member, value in e.members:
                lines.append(f'    {member} = {value}')
            lines.append('')
        return '\n'.join(lines) + '\n'

    def render_builders(self) -> str:
        lines = [HEADER.format(title='Keyword-only constructors for IEEE 2030.5 resources.', source=self.source_note)]
        lines.append('from __future__ import annotations\n')
        lines.append('from typing import Any\n')
        lines.append('from .sep import *  # noqa: F401,F403\n')
        names: list[str] = []
        for spec in sorted(self.ordered(), key=lambda s: s.name):
            if not self.wants_builder(spec):
                continue
            fields = [f for f in self.all_fields(spec) if not f.extra.get('revision_marker')]
            fname = 'build_' + snake_case(spec.name)
            names.append(fname)
            lines.append(f'\ndef {fname}(')
            lines.append('    *,')
            for f in fields:
                lines.append(f'    {f.name}: {f.builder_annotation} = None,')
            lines.append(f') -> {spec.name}:')
            lines.append('    ' + docstring(f'Build an IEEE 2030.5 ``{spec.xml_name or spec.name}``. {spec.doc}'.rstrip()))
            lines.append(f'    return {spec.name}(')
            for f in fields:
                if f.annotation.startswith('list['):
                    lines.append(f'        {f.name}={f.name} if {f.name} is not None else [],')
                else:
                    lines.append(f'        {f.name}={f.name},')
            lines.append('    )\n')
        lines.append('\n__all__ = [')
        for n in names:
            lines.append(f'    {n!r},')
        lines.append(']')
        return '\n'.join(lines) + '\n'

