"""Generate pydantic models and profile builders for IEEE 2030.5 (SEP 2.0).

Source: the IEEE 2030.5 ``sep.xsd`` schema from the standard's supplemental material, rendered to
``xsdata`` dataclasses with the schema's own class and field names (``--schema``; xsdata is run by this
script with the configuration in ``XSDATA_CONFIG``). The models follow the newest edition (2023), a
superset of 2018; ``editions.py`` records which types and fields each edition (2013, 2018, 2023)
defines so a remote can be treated as a profile of the superset. Enumerations come from the
``enums.py`` and ``constants.py`` that Eclipse VOLTTRON wrote from the schema's documentation
(Apache-2.0; vendored under ``sources/ieee2030_5/``), since the schema documents its enumerations
in prose rather than as facets.

Run from the ``interoperability_service`` directory (as a script, so a broken generated module
cannot stop regeneration)::

    python src/interoperability/models/ieee2030_5/generate_models.py
        [--schema 1547_standards/2030.5/2023/.../sep.xsd]        # default: the newest edition found
        [--editions 2013=PATH 2018=PATH 2023=PATH]                # default: every sep.xsd under 1547_standards/2030.5
        [--source-dir DIR]                                        # pre-rendered xsdata output instead of --schema
        [--enums-dir DIR] [--out DIR]

Requires ``xsdata[cli]`` when ``--schema`` is used (``pip install "xsdata[cli]"``).

Outputs, all overwritten in place:

* ``sep.py``               every schema type as a pydantic model, in dependency order
* ``enums.py``             the enumerations the source defines
* ``editions.py``          per-edition type and field membership, namespaces, curve types and control modes
* ``profile_builders.py``  ``build_<resource>(...)`` keyword-only constructors
* ``__init__.py``          package exports

The ``*_r2_3`` elements the 2023 schema adds to every type are revision markers (an ``xs:any`` extension
point); they are kept on the models for wire fidelity, flagged ``revision_marker`` in their metadata, and
left out of the builders and the field universe.
"""
