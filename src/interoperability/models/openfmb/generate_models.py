"""Generate pydantic models for OpenFMB profiles from the OpenFMB protobuf PSM.

Source: the OpenFMB Users Group ``psm-protobuf-python`` repository (generated Python bindings
for the OpenFMB Platform Specific Model, v2.2), a copy of which lives at
``1547_standards/openfmb/psm-protobuf-python`` in this workspace (the standards share). The protobuf descriptors are the authority
for message shapes; the classes here mirror protobuf's JSON mapping, which is what OpenFMB
adapters publish on MQTT and NATS: field names as in the ``.proto`` files, enumerations by
name, well-known wrapper types collapsed to their scalar, 64 bit integers accepted as strings
or numbers.

Requires ``protobuf>=6.31`` (7.x works) at generation time only; the generated package depends on pydantic
alone. Run from the ``interoperability_service`` directory::

    PYTHONPATH=/path/with/protobuf python src/interoperability/models/openfmb/generate_models.py \\
        [--source ../1547_standards/openfmb/psm-protobuf-python/openfmb] [--out src/interoperability/models/openfmb]

Outputs, all overwritten in place:

* ``<name>_module/__init__.py``  one package per OpenFMB module (``essmodule`` -> ``ess_module``)
  with an ``Enum`` per enumeration and a pydantic class per message, profiles included
* ``__init__.py``                 package exports plus the ``PROFILES`` registry (``_base.py`` is hand-written)
* ``generated_manifest.json``     module, message and enum counts for the record

``profile_builders.py`` and ``generate_samples.py`` are hand-written and not touched.
"""
from __future__ import annotations

import argparse
import importlib
import json
import os
import keyword
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_SOURCE = HERE.parents[4] / '1547_standards' / 'openfmb' / 'psm-protobuf-python' / 'openfmb'

# Protobuf module name -> generated package name. Matches the directories the earlier package used.
PACKAGE_NAMES = {
    'breakermodule': 'breaker_module', 'capbankmodule': 'cap_bank_module',
    'circuitsegmentservicemodule': 'circuit_segment_service_module', 'commonmodule': 'common_module',
    'environmentmodule': 'environment_module', 'essmodule': 'ess_module', 'evsemodule': 'evse_module',
    'generationmodule': 'generation_module', 'interconnectionmodule': 'interconnection_module',
    'loadmodule': 'load_module', 'metermodule': 'meter_module', 'reclosermodule': 'recloser_module',
    'regulatormodule': 'regulator_module', 'reservemodule': 'reserve_module', 'resourcemodule': 'resource_module',
    'solarmodule': 'solar_module', 'switchmodule': 'switch_module',
}

WRAPPERS = {
    'google.protobuf.BoolValue': 'bool', 'google.protobuf.DoubleValue': 'float', 'google.protobuf.FloatValue': 'float',
    'google.protobuf.Int32Value': 'int', 'google.protobuf.Int64Value': 'int', 'google.protobuf.UInt32Value': 'int',
    'google.protobuf.UInt64Value': 'int', 'google.protobuf.StringValue': 'str', 'google.protobuf.BytesValue': 'str',
}

HEADER = '''"""OpenFMB ``{proto}`` messages as pydantic models.

Generated by ``generate_models.py`` from the OpenFMB protobuf PSM; do not edit by hand. Field
names follow the protobuf JSON mapping. Unknown fields are rejected so that messages of the
wrong shape fail validation instead of matching nothing.
"""
from __future__ import annotations

from enum import Enum
from typing import Any, ClassVar

from pydantic import Field

from .._base import OpenFMBMessage
{imports}
'''


def _scalar_type(field) -> str:
    from google.protobuf.descriptor import FieldDescriptor as FD
    if field.type in (FD.TYPE_DOUBLE, FD.TYPE_FLOAT):
        return 'float'
    if field.type == FD.TYPE_BOOL:
        return 'bool'
    if field.type in (FD.TYPE_STRING, FD.TYPE_BYTES):
        return 'str'
    return 'int'


def _proto_type_name(field) -> str:
    from google.protobuf.descriptor import FieldDescriptor as FD
    if field.type == FD.TYPE_MESSAGE:
        return field.message_type.full_name
    if field.type == FD.TYPE_ENUM:
        return field.enum_type.full_name
    return {FD.TYPE_DOUBLE: 'double', FD.TYPE_FLOAT: 'float', FD.TYPE_INT32: 'int32', FD.TYPE_INT64: 'int64',
            FD.TYPE_UINT32: 'uint32', FD.TYPE_UINT64: 'uint64', FD.TYPE_SINT32: 'sint32', FD.TYPE_SINT64: 'sint64',
            FD.TYPE_FIXED32: 'fixed32', FD.TYPE_FIXED64: 'fixed64', FD.TYPE_SFIXED32: 'sfixed32',
            FD.TYPE_SFIXED64: 'sfixed64', FD.TYPE_BOOL: 'bool', FD.TYPE_STRING: 'string',
            FD.TYPE_BYTES: 'bytes'}.get(field.type, str(field.type))


def _identifier(name: str) -> str:
    ident = re.sub(r'\W', '_', name)
    if not ident or ident[0].isdigit():
        ident = '_' + ident
    if keyword.iskeyword(ident):
        ident += '_'
    return ident


def _python_field_name(name: str, reserved: set[str]) -> tuple[str, bool]:
    """Python attribute for a protobuf field, aliased to the wire name when the field would shadow a
    pydantic attribute or a class or enum name in the module (annotations are evaluated in class scope)."""
    from pydantic import BaseModel
    ident = _identifier(name)
    if ident != name:
        return ident, True
    if hasattr(BaseModel, ident) or ident in reserved:
        return ident + '_', True
    return ident, False


def _all_messages(descriptor):
    """Top-level and nested message descriptors of a file, with the class name each will get."""
    for message in descriptor.message_types_by_name.values():
        yield from _with_nested(message, message.name)


def _with_nested(message, name):
    yield name, message
    for nested in message.nested_types:
        yield from _with_nested(nested, f'{name}_{nested.name}')


def _topological(items: dict[str, set[str]]) -> list[str]:
    """Order names so that every dependency precedes its dependents (dependencies outside ``items`` ignored)."""
    order, done = [], set()

    def visit(name, stack=()):
        if name in done:
            return
        if name in stack:
            raise ValueError(f'Cycle among {stack + (name,)}')
        for dep in sorted(items[name]):
            if dep in items:
                visit(dep, stack + (name,))
        done.add(name)
        order.append(name)

    for name in sorted(items):
        visit(name)
    return order


class ModuleSpec:
    def __init__(self, proto_name: str, descriptor):
        self.proto_name = proto_name
        self.package = PACKAGE_NAMES[proto_name]
        self.descriptor = descriptor
        self.messages = dict(_all_messages(descriptor))                 # class name -> descriptor
        self.enums = {e.name: e for e in descriptor.enum_types_by_name.values()}
        for message in self.messages.values():
            for enum in message.enum_types:
                self.enums[f'{message.name}_{enum.name}'] = enum
        self.depends_on: set[str] = set()
        for message in self.messages.values():
            for field in message.fields:
                target = field.message_type if field.message_type is not None else field.enum_type
                if target is not None and not target.file.package.startswith('google.'):
                    if target.file.package != proto_name:
                        self.depends_on.add(target.file.package)
        self.class_names = {d.full_name: n for n, d in self.messages.items()}
        self.enum_names = {e.full_name: n for n, e in self.enums.items()}


def _type_reference(spec: ModuleSpec, specs: dict[str, ModuleSpec], full_name: str, is_enum: bool) -> str:
    """How a message or enum type is written inside ``spec``'s module."""
    package = full_name.rsplit('.', 1)[0] if '.' in full_name else ''
    owner = specs[package]
    name = owner.enum_names[full_name] if is_enum else owner.class_names[full_name]
    return name if owner is spec else f'_{owner.package}.{name}'


def render_module(spec: ModuleSpec, specs: dict[str, ModuleSpec]) -> str:
    from google.protobuf.descriptor import FieldDescriptor as FD
    imports = ''.join(f'from .. import {PACKAGE_NAMES[dep]} as _{PACKAGE_NAMES[dep]}\n' for dep in sorted(spec.depends_on))
    out = [HEADER.format(proto=spec.proto_name, imports=imports)]
    for name, enum in sorted(spec.enums.items()):
        out.append(f'\nclass {name}(str, Enum):\n    """OpenFMB enumeration ``{enum.full_name}``."""\n')
        for value in enum.values:
            out.append(f"    {_identifier(value.name)} = '{value.name}'\n")
    # Classes in dependency order so annotations resolve as they are read.
    deps = {name: {spec.class_names[f.message_type.full_name] for f in desc.fields
                   if f.type == FD.TYPE_MESSAGE and f.message_type.full_name in spec.class_names}
            for name, desc in spec.messages.items()}
    reserved = set(spec.messages) | set(spec.enums) | {'Any', 'ClassVar', 'Field', 'BaseModel', 'ConfigDict', 'Enum',
                                                          'OpenFMBMessage', 'PROFILES'} | {f'_{PACKAGE_NAMES[d]}' for d in spec.depends_on}
    for name in _topological(deps):
        desc = spec.messages[name]
        profile = name.endswith('Profile')
        out.append(f'\nclass {name}(OpenFMBMessage):\n    """OpenFMB {"profile" if profile else "message"} ``{desc.full_name}``."""\n'
                   f"    PROTO: ClassVar[str] = '{desc.full_name}'\n")
        if profile:
            out.append('    PROFILE: ClassVar[bool] = True\n')
        if not desc.fields:
            out.append('    pass\n')
        for field in desc.fields:
            attr, aliased = _python_field_name(field.name, reserved)
            # protobuf 7 removed ``FieldDescriptor.label``; ``is_repeated`` exists from 6.x on.
            repeated = field.is_repeated if hasattr(field, 'is_repeated') else field.label == FD.LABEL_REPEATED
            extra = {'proto': _proto_type_name(field)}
            if field.type == FD.TYPE_MESSAGE and field.message_type.full_name in WRAPPERS:
                base = WRAPPERS[field.message_type.full_name]
                extra['wrapper'] = field.message_type.name
            elif field.type == FD.TYPE_MESSAGE and field.message_type.full_name.startswith('google.'):
                base = 'Any'
            elif field.type == FD.TYPE_MESSAGE:
                base = _type_reference(spec, specs, field.message_type.full_name, is_enum=False)
            elif field.type == FD.TYPE_ENUM:
                base = _type_reference(spec, specs, field.enum_type.full_name, is_enum=True) + ' | int'
            else:
                base = _scalar_type(field)
            args = [f"alias='{field.name}'"] if aliased else []
            if ' | int' in base:
                args.append("union_mode='left_to_right'")
            args.append(f'json_schema_extra={extra!r}')
            if repeated:
                annotation, default = f'list[{base}]', 'default_factory=list'
            else:
                annotation, default = f'{base} | None', 'default=None'
            out.append(f'    {attr}: {annotation} = Field({default}, {", ".join(args)})\n')
    out.append('\n\nPROFILES = {' + ', '.join(f"'{n}': {n}" for n in sorted(spec.messages) if n.endswith('Profile')) + '}\n')
    out.append('__all__ = [' + ', '.join(f"'{n}'" for n in sorted(list(spec.messages) + list(spec.enums))) + ']\n')
    return ''.join(out)


def render_package(specs: dict[str, ModuleSpec]) -> str:
    lines = ['"""OpenFMB profiles as pydantic models, generated from the OpenFMB protobuf PSM by ``generate_models.py``.\n\n'
             'Every module package (``ess_module``, ``solar_module``, ...) holds one class per protobuf message and one\n'
             '``Enum`` per enumeration. ``PROFILES`` maps every profile class name to its class.\n"""\n',
             'from __future__ import annotations\n\nfrom ._base import OpenFMBMessage\n']
    for proto in _topological({p: s.depends_on for p, s in specs.items()}):
        lines.append(f'from . import {specs[proto].package}\n')
    lines.append('\nPROFILES: dict[str, type] = {}\n__all__ = []\n')
    for proto in _topological({p: s.depends_on for p, s in specs.items()}):
        pkg = specs[proto].package
        lines.append(f'PROFILES.update({pkg}.PROFILES)\n__all__ += {pkg}.__all__\n'
                     f'globals().update({{name: getattr({pkg}, name) for name in {pkg}.__all__}})\n')
    lines.append("__all__ = sorted(set(__all__)) + ['OpenFMBMessage', 'PROFILES']\n")
    return ''.join(lines)


def load_specs(source: Path) -> dict[str, ModuleSpec]:
    sys.path.insert(0, str(source))
    specs = {}
    for proto in sorted(PACKAGE_NAMES):
        module = importlib.import_module(f'{proto}.{proto}_pb2')
        specs[proto] = ModuleSpec(proto, module.DESCRIPTOR)
    return specs


def generate(source: Path, out: Path) -> dict:
    specs = load_specs(source)
    for spec in specs.values():
        package_dir = out / spec.package
        package_dir.mkdir(parents=True, exist_ok=True)
        (package_dir / '__init__.py').write_text(render_module(spec, specs))
    (out / '__init__.py').write_text(render_package(specs))
    # Recorded relative to the package so the manifest does not depend on where the workspace lives.
    manifest = {'source': os.path.relpath(source, out), 'modules': {s.package: {'proto': p, 'messages': len(s.messages), 'enums': len(s.enums),
                                                              'profiles': sum(n.endswith('Profile') for n in s.messages)}
                                                  for p, s in specs.items()}}
    (out / 'generated_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    return manifest


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--source', type=Path, default=DEFAULT_SOURCE, help='psm-protobuf-python/openfmb directory')
    parser.add_argument('--out', type=Path, default=HERE, help='package directory to write')
    args = parser.parse_args(argv)
    manifest = generate(args.source, args.out)
    for package, counts in manifest['modules'].items():
        print(f"{package:<32} {counts['messages']:4d} messages {counts['enums']:3d} enums {counts['profiles']:3d} profiles")


if __name__ == '__main__':
    main()
