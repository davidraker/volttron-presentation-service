"""Generate pydantic models and profile builders from the SunSpec model definitions.

Source: the SunSpec Alliance ``models`` repository (https://github.com/sunspec/models, ``json/model_*.json``).
By default the copy the installed ``pysunspec2`` package ships is used (the same repository's content, possibly at an
older commit); pass ``--source`` or set ``SUNSPEC_MODELS`` to the ``json`` directory of a clone for a chosen revision.

Run from the ``interoperability_service`` directory (as a script, so a broken generated module
cannot stop regeneration)::

    python src/interoperability/models/sunspec/generate_models.py [--source DIR] [--out DIR]

Outputs, all overwritten in place:

* ``models/model_<id>.py``  one module per SunSpec model with enum / flag classes, nested
  group classes and the model class itself
* ``models/__init__.py``    imports every model module and re-exports every class
* ``profile_builders.py``   ``build_<model_name>(...)`` keyword-only constructors
* ``__init__.py``           package exports
"""
from __future__ import annotations

import argparse
import json
import os
import keyword
import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from pydantic import BaseModel

HERE = Path(__file__).resolve().parent


def _load_common():
    """Import ``common.py`` by path so the generator runs even if the generated modules are broken."""
    import importlib.util
    spec = importlib.util.spec_from_file_location('_sunspec_common', HERE / 'common.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)  # type: ignore[union-attr]
    return module


_common = _load_common()
BITFIELD_TYPES, ENUM_TYPES, FLOAT_TYPES, INTEGER_TYPES, STRING_TYPES = (
    _common.BITFIELD_TYPES, _common.ENUM_TYPES, _common.FLOAT_TYPES, _common.INTEGER_TYPES, _common.STRING_TYPES,
)
SOURCE_ENV = 'SUNSPEC_MODELS'


def default_source() -> Path | None:
    """``$SUNSPEC_MODELS``, else the model JSON shipped by the installed pysunspec2 package."""
    if os.environ.get(SOURCE_ENV):
        return Path(os.environ[SOURCE_ENV]).expanduser()
    try:
        import sunspec2
    except ImportError:
        return None
    return Path(sunspec2.__file__).resolve().parent / 'models' / 'json'

HEADER = '"""{title}\n\nGenerated by ``interoperability.models.sunspec.generate_models``. Do not edit by hand.\n"""\n'

RESERVED_FIELD_NAMES = set(dir(BaseModel)) | set(keyword.kwlist) | {'GROUP_NAME', 'MODEL_ID', 'MODEL_LABEL'}


# --------------------------------------------------------------------------------------
# Name helpers
# --------------------------------------------------------------------------------------
def class_name(name: str) -> str:
    """SunSpec group names are already identifiers; just make sure they start upper-case."""
    txt = re.sub(r'[^A-Za-z0-9_]', '_', name)
    if not txt:
        txt = 'Group'
    if txt[0].isdigit():
        txt = '_' + txt
    return txt[0].upper() + txt[1:]


def snake_case(name: str) -> str:
    txt = re.sub(r'(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])', '_', name)
    txt = re.sub(r'[^A-Za-z0-9]+', '_', txt).strip('_').lower()
    return re.sub(r'_+', '_', txt)


def field_name(name: str, taken: set[str]) -> str:
    txt = re.sub(r'[^A-Za-z0-9_]', '_', name)
    if not txt or txt[0].isdigit():
        txt = 'P' + txt
    if txt.startswith('_'):
        txt = 'P' + txt
    if txt in RESERVED_FIELD_NAMES:
        txt = txt + '_'
    base, n = txt, 2
    while txt in taken:
        txt = f'{base}{n}'
        n += 1
    taken.add(txt)
    return txt


def symbol_name(name: str, taken: set[str]) -> str:
    txt = str(name).replace('%', 'PCT_').replace('+', '_PLUS_').replace('&', '_AND_')
    txt = re.sub(r'[^A-Za-z0-9_]', '_', txt)
    txt = re.sub(r'_+', '_', txt).strip('_').upper()
    if not txt:
        txt = 'VALUE'
    if txt[0].isdigit():
        txt = '_' + txt
    if keyword.iskeyword(txt) or txt in {'MRO', 'NAME', 'VALUE'}:
        txt = txt + '_'
    base, n = txt, 2
    while txt in taken:
        txt = f'{base}_{n}'
        n += 1
    taken.add(txt)
    return txt


def py_literal(value: Any) -> str:
    return repr(value)


# --------------------------------------------------------------------------------------
# Intermediate representation
# --------------------------------------------------------------------------------------
@dataclass
class EnumSpec:
    name: str
    kind: str    # 'enum' or 'flags'
    members: list[tuple[str, int, str]]    # (member, value, label/desc)
    doc: str


@dataclass
class FieldSpec:
    name: str
    point_name: str
    annotation: str
    default: str
    description: str
    extra: dict[str, Any]
    union_left_to_right: bool = False
    builder_annotation: str = ''


@dataclass
class GroupSpec:
    name: str
    sunspec_name: str
    doc: str
    fields: list[FieldSpec] = field(default_factory=list)
    children: list[GroupSpec] = field(default_factory=list)
    is_model: bool = False
    model_id: int = 0
    label: str = ''


@dataclass
class ModuleSpec:
    model_id: int
    module_name: str
    enums: list[EnumSpec] = field(default_factory=list)
    groups: list[GroupSpec] = field(default_factory=list)    # in definition order, leaves first
    model_class: str = ''


class Generator:

    def __init__(self, source: Path):
        self.source = source
        self.all_class_names: dict[str, str] = {}    # class -> module

    def unique_class(self, name: str, module: str) -> str:
        base, n = name, 2
        while name in self.all_class_names:
            name = f'{base}{n}'
            n += 1
        self.all_class_names[name] = module
        return name

    # ---- per-model -------------------------------------------------------------------
    def build_module(self, definition: dict[str, Any]) -> ModuleSpec:
        model_id = int(definition['id'])
        module = ModuleSpec(model_id=model_id, module_name=f'model_{model_id}')
        top = definition['group']
        root = self.build_group(top, parent_class='', module=module, is_model=True, model_id=model_id)
        module.model_class = root.name
        return module

    def build_group(self, group: dict[str, Any], parent_class: str, module: ModuleSpec, *,
                    is_model: bool = False, model_id: int = 0) -> GroupSpec:
        base = class_name(group['name'])
        cls = self.unique_class(base if is_model else parent_class + base, module.module_name)
        spec = GroupSpec(
            name=cls,
            sunspec_name=group['name'],
            doc=(group.get('desc') or group.get('label') or group['name']).strip(),
            is_model=is_model,
            model_id=model_id,
            label=(group.get('label') or group['name']).strip(),
        )
        taken: set[str] = set()
        if is_model:
            taken.update({'ID', 'L'})
        children: list[tuple[GroupSpec, dict[str, Any]]] = []
        # Nested groups first so their classes are emitted before the parent uses them.
        for child in group.get('groups', []) or []:
            child_spec = self.build_group(child, cls, module)
            children.append((child_spec, child))
        for point in group.get('points', []) or []:
            if is_model and point['name'] in ('ID', 'L'):
                # Provided by SunSpecModel; only the fixed model id default differs.
                continue
            spec.fields.append(self.build_field(point, cls, taken, module))
        for child_spec, child in children:
            spec.children.append(child_spec)
            spec.fields.append(self.build_group_field(child_spec, child, taken))
        module.groups.append(spec)
        return spec

    def build_field(self, point: dict[str, Any], owner: str, taken: set[str], module: ModuleSpec) -> FieldSpec:
        ptype = point['type']
        name = field_name(point['name'], taken)
        extra: dict[str, Any] = {'type': ptype, 'size': point.get('size')}
        for key in ('units', 'sf', 'access', 'mandatory', 'static', 'label', 'standards'):
            if point.get(key) not in (None, '', []):
                extra[key] = point[key]
        description = (point.get('desc') or point.get('label') or point['name']).strip()
        default = 'None'
        ltr = False
        builder_annotation = ''
        if ptype in ENUM_TYPES and point.get('symbols'):
            enum_name = self.add_enum(point, owner, module, 'enum')
            annotation = f'{enum_name} | int | None'
            builder_annotation = annotation
            ltr = True
        elif ptype in BITFIELD_TYPES and point.get('symbols'):
            enum_name = self.add_enum(point, owner, module, 'flags')
            annotation = f'{enum_name} | int | None'
            builder_annotation = annotation
            ltr = True
        elif ptype in ENUM_TYPES or ptype in BITFIELD_TYPES or ptype in INTEGER_TYPES:
            annotation = 'int | None'
        elif ptype in FLOAT_TYPES:
            annotation = 'float | None'
        elif ptype in STRING_TYPES:
            annotation = 'str | None'
        else:
            raise ValueError(f'Unhandled SunSpec point type {ptype!r} for {owner}.{point["name"]}')
        if 'value' in point and point['value'] is not None:
            default = py_literal(point['value'])
            extra['fixed_value'] = point['value']
        return FieldSpec(
            name=name,
            point_name=point['name'],
            annotation=annotation,
            default=default,
            description=description,
            extra=extra,
            union_left_to_right=ltr,
            builder_annotation=builder_annotation or annotation,
        )

    def build_group_field(self, child: GroupSpec, group: dict[str, Any], taken: set[str]) -> FieldSpec:
        name = field_name(group['name'], taken)
        count = group.get('count')
        extra: dict[str, Any] = {'type': 'group', 'group_type': group.get('type', 'group')}
        if count is not None:
            extra['count'] = count
        repeating = count is not None and str(count) != '1'
        if repeating:
            annotation = f'list[{child.name}]'
            default = 'Field(default_factory=list)'
            builder_annotation = f'list[{child.name} | dict[str, Any]] | None'
        else:
            annotation = f'{child.name} | None'
            default = 'None'
            builder_annotation = f'{child.name} | dict[str, Any] | None'
        return FieldSpec(
            name=name,
            point_name=group['name'],
            annotation=annotation,
            default=default,
            description=(group.get('desc') or group.get('label') or group['name']).strip(),
            extra=extra,
            builder_annotation=builder_annotation,
        )

    def add_enum(self, point: dict[str, Any], owner: str, module: ModuleSpec, kind: str) -> str:
        name = self.unique_class(owner + class_name(point['name']), module.module_name)
        taken: set[str] = set()
        members: list[tuple[str, int, str]] = []
        for sym in point['symbols']:
            raw = sym.get('value')
            try:
                value = int(raw)
            except (TypeError, ValueError):
                continue
            if kind == 'flags':
                value = 1 << value
            members.append((symbol_name(sym['name'], taken), value, (sym.get('label') or sym.get('desc') or sym['name']).strip()))
        doc = f"{'Bitfield' if kind == 'flags' else 'Enumeration'} for point ``{owner}.{point['name']}`` ({point['type']})."
        spec = EnumSpec(name=name, kind=kind, members=members, doc=doc)
        module.enums.append(spec)
        return name

    # ---- rendering -------------------------------------------------------------------
    @staticmethod
    def render_field(f: FieldSpec) -> str:
        args = []
        if f.default.startswith('Field('):
            # default_factory form
            inner = f.default[len('Field('):-1]
            args.append(inner)
        else:
            args.append(f'default={f.default}')
        args.append(f'description={py_literal(f.description)}')
        if f.union_left_to_right:
            args.append("union_mode='left_to_right'")
        args.append(f'json_schema_extra={py_literal(f.extra)}')
        return f'    {f.name}: {f.annotation} = Field({", ".join(args)})'

    def render_module(self, module: ModuleSpec, definition: dict[str, Any]) -> str:
        model = module.groups[-1]
        lines = [HEADER.format(title=f"SunSpec model {module.model_id}: {model.label}")]
        lines.append('from __future__ import annotations\n')
        lines.append('from typing import Any, ClassVar\n')
        lines.append('from pydantic import Field\n')
        lines.append('from ..common import SunSpecEnum, SunSpecFlags, SunSpecGroup, SunSpecModel, register_model\n')
        lines.append('__all__ = [')
        names = [e.name for e in module.enums] + [g.name for g in module.groups]
        for n in sorted(names):
            lines.append(f'    {py_literal(n)},')
        lines.append(']\n')
        for e in module.enums:
            base = 'SunSpecFlags' if e.kind == 'flags' else 'SunSpecEnum'
            lines.append(f'\nclass {e.name}({base}):')
            lines.append(f'    """{e.doc}"""')
            if not e.members:
                lines.append('    pass')
            for member, value, label in e.members:
                lines.append(f'    {member} = {value}    # {label}' if label != member else f'    {member} = {value}')
            lines.append('')
        for g in module.groups:
            if g.is_model:
                lines.append('\n@register_model')
                lines.append(f'class {g.name}(SunSpecModel):')
            else:
                lines.append(f'\nclass {g.name}(SunSpecGroup):')
            lines.append(f'    """{g.doc}"""\n')
            lines.append(f'    GROUP_NAME: ClassVar[str] = {py_literal(g.sunspec_name)}')
            if g.is_model:
                lines.append(f'    MODEL_ID: ClassVar[int] = {g.model_id}')
                lines.append(f'    MODEL_LABEL: ClassVar[str] = {py_literal(g.label)}\n')
                id_point = next(p for p in definition['group']['points'] if p['name'] == 'ID')
                l_point = next(p for p in definition['group']['points'] if p['name'] == 'L')
                lines.append(f'    ID: int | None = Field(default={g.model_id}, description={py_literal((id_point.get("desc") or "Model ID").strip())}, json_schema_extra={py_literal({"type": id_point["type"], "size": id_point.get("size"), "mandatory": id_point.get("mandatory"), "static": id_point.get("static"), "fixed_value": g.model_id})})')
                lines.append(f'    L: int | None = Field(default=None, description={py_literal((l_point.get("desc") or "Model length").strip())}, json_schema_extra={py_literal({"type": l_point["type"], "size": l_point.get("size"), "mandatory": l_point.get("mandatory"), "static": l_point.get("static")})})')
            else:
                lines.append('')
            for f in g.fields:
                lines.append(self.render_field(f))
            if not g.fields and not g.is_model:
                lines.append('    pass')
            lines.append('')
        return '\n'.join(lines).rstrip() + '\n'

    def render_models_init(self, modules: list[ModuleSpec]) -> str:
        lines = [HEADER.format(title='Generated SunSpec model classes, one module per model id.')]
        lines.append('from __future__ import annotations\n')
        exports: list[str] = []
        for m in sorted(modules, key=lambda x: x.model_id):
            lines.append(f'from .{m.module_name} import *  # noqa: F401,F403')
            exports.extend(e.name for e in m.enums)
            exports.extend(g.name for g in m.groups)
        lines.append('')
        lines.append('__all__ = [')
        for n in sorted(exports):
            lines.append(f'    {py_literal(n)},')
        lines.append(']')
        return '\n'.join(lines) + '\n'

    def render_builders(self, modules: list[ModuleSpec]) -> str:
        lines = [HEADER.format(title='Keyword-only constructors for every SunSpec model and group.')]
        lines.append('from __future__ import annotations\n')
        lines.append('from typing import Any\n')
        lines.append('from .common import SunSpecDevice, SunSpecModel')
        lines.append('from .models import *  # noqa: F401,F403\n')
        lines.append('\ndef build_sunspec_device(*models: SunSpecModel | dict[str, Any], **by_id: SunSpecModel | dict[str, Any]) -> SunSpecDevice:')
        lines.append('    """Assemble a :class:`SunSpecDevice` from model instances or ``{model_id: payload}`` keywords.\n')
        lines.append('    Positional arguments must be model instances (their ``MODEL_ID`` is the key). Keyword')
        lines.append('    arguments are keyed by model id as a string, for example ``build_sunspec_device(**{"701": {...}})``.')
        lines.append('    """')
        lines.append('    payload: dict[int, Any] = {}')
        lines.append('    for model in models:')
        lines.append('        if isinstance(model, SunSpecModel):')
        lines.append('            payload[model.ID if model.ID is not None else model.MODEL_ID] = model')
        lines.append('        elif isinstance(model, dict) and model.get("ID") is not None:')
        lines.append('            payload[int(model["ID"])] = model')
        lines.append('        else:')
        lines.append("            raise ValueError('Positional models must be SunSpecModel instances or dicts with an ID')")
        lines.append('    for key, value in by_id.items():')
        lines.append('        payload[int(key)] = value')
        lines.append('    return SunSpecDevice.model_validate(payload)\n')
        builder_names = ['build_sunspec_device']
        used: set[str] = set(builder_names)
        for m in sorted(modules, key=lambda x: x.model_id):
            for g in m.groups:
                fname = 'build_' + snake_case(g.name)
                if g.is_model:
                    fname = f'build_model_{m.model_id}_{snake_case(g.name)}'
                base, n = fname, 2
                while fname in used:
                    fname = f'{base}_{n}'
                    n += 1
                used.add(fname)
                builder_names.append(fname)
                lines.append(f'\ndef {fname}(')
                lines.append('    *,')
                if g.is_model:
                    lines.append(f'    ID: int | None = {m.model_id},')
                    lines.append('    L: int | None = None,')
                for f in g.fields:
                    lines.append(f'    {f.name}: {f.builder_annotation} = None,')
                lines.append(f') -> {g.name}:')
                what = f'SunSpec model {m.model_id} ({g.sunspec_name})' if g.is_model else f'group ``{g.sunspec_name}`` of SunSpec model {m.model_id}'
                lines.append(f'    """Build {what}: {g.doc}"""')
                lines.append(f'    return {g.name}(')
                if g.is_model:
                    lines.append('        ID=ID,')
                    lines.append('        L=L,')
                for f in g.fields:
                    if f.annotation.startswith('list['):
                        lines.append(f'        {f.name}={f.name} if {f.name} is not None else [],')
                    else:
                        lines.append(f'        {f.name}={f.name},')
                lines.append('    )\n')
        lines.append('\n__all__ = [')
        for n in builder_names:
            lines.append(f'    {py_literal(n)},')
        lines.append(']')
        return '\n'.join(lines) + '\n'

    def render_package_init(self, modules: list[ModuleSpec]) -> str:
        lines = ['"""Pydantic models of the SunSpec Modbus information model.\n']
        lines.append('The classes are generated from the SunSpec Alliance model definitions by')
        lines.append('``generate_models.py``; see that module for how to regenerate them. ``common`` holds the')
        lines.append('shared base classes and the ``SunSpecDevice`` container, ``models`` the per-model classes')
        lines.append('and ``profile_builders`` keyword-only constructors for each model and group.')
        lines.append('"""')
        lines.append('from __future__ import annotations\n')
        lines.append('from .common import (')
        for n in ('MODEL_REGISTRY', 'SunSpecDevice', 'SunSpecEnum', 'SunSpecFlags', 'SunSpecGroup', 'SunSpecModel', 'model_class', 'register_model'):
            lines.append(f'    {n},')
        lines.append(')')
        lines.append('from .models import *  # noqa: F401,F403')
        lines.append('from .models import __all__ as _model_names')
        lines.append('from .profile_builders import *  # noqa: F401,F403')
        lines.append('from .profile_builders import __all__ as _builder_names\n')
        lines.append("__all__ = [")
        for n in ('MODEL_REGISTRY', 'SunSpecDevice', 'SunSpecEnum', 'SunSpecFlags', 'SunSpecGroup', 'SunSpecModel', 'model_class', 'register_model'):
            lines.append(f'    {py_literal(n)},')
        lines.append('    *_model_names,')
        lines.append('    *_builder_names,')
        lines.append(']')
        return '\n'.join(lines) + '\n'


def load_definitions(source: Path) -> list[dict[str, Any]]:
    defs = []
    for path in sorted(source.glob('model_*.json'), key=lambda p: int(p.stem.split('_')[1])):
        with path.open(encoding='utf-8') as fh:
            defs.append(json.load(fh))
    if not defs:
        raise SystemExit(f'No model_*.json files found in {source}')
    return defs


def generate(source: Path, out: Path) -> list[ModuleSpec]:
    gen = Generator(source)
    definitions = load_definitions(source)
    modules: list[ModuleSpec] = []
    models_dir = out / 'models'
    models_dir.mkdir(parents=True, exist_ok=True)
    for stale in models_dir.glob('model_*.py'):
        stale.unlink()
    for definition in definitions:
        module = gen.build_module(definition)
        modules.append(module)
        (models_dir / f'{module.module_name}.py').write_text(gen.render_module(module, definition), encoding='utf-8')
    (models_dir / '__init__.py').write_text(gen.render_models_init(modules), encoding='utf-8')
    (out / 'profile_builders.py').write_text(gen.render_builders(modules), encoding='utf-8')
    (out / '__init__.py').write_text(gen.render_package_init(modules), encoding='utf-8')
    return modules


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--source', type=Path, default=None, help=f'directory of SunSpec model_*.json files (default: ${SOURCE_ENV}, else pysunspec2\'s copy)')
    parser.add_argument('--out', type=Path, default=HERE, help='package directory to write into')
    args = parser.parse_args(argv)
    if args.source is None:
        args.source = default_source()
        if args.source is None:
            raise SystemExit(f'Set {SOURCE_ENV} to the json directory of a sunspec/models clone, install pysunspec2, or pass --source.')
    modules = generate(args.source, args.out)
    n_groups = sum(len(m.groups) for m in modules)
    n_enums = sum(len(m.enums) for m in modules)
    print(f'Generated {len(modules)} SunSpec models ({n_groups} group classes, {n_enums} enum/flag classes) into {args.out}')


if __name__ == '__main__':
    main()
