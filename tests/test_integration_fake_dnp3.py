"""Integration: an IEEE 1815.2 (MESA-DER) outstation described by a profile, driven by the fake driver and used
through SunSpec, IEEE 2030.5 and IEC 61850, with scale factors applied by the transform or by the driver.

Everything under ``tests/integration/fake_dnp3/<mode>_scaling/`` is generated by ``build_configs.py`` from the
test tool's "mandatory for 1547" profile. Reads go device -> 1815.2.inputs -> alias format; writes come back
2030.5 -> 1815.2.outputs -> device, with the curve edit window as ordered batches of flat points.
"""
from __future__ import annotations

import csv
import json
from importlib import resources
from pathlib import Path

import pytest

from interoperability import field_universe
from interoperability.discovery.device_formats import dnp3_device_transforms, dnp3_point_path, dnp3_scaling
from interoperability.discovery.dnp3 import discover_indexes, discover_profile, dnp3_registry_rows, fake_registry_rows
from interoperability.mapping_engine import UAITree
from interoperability.discovery.point_maps import ieee2030_5_point_map
from interoperability.transform_parser import TransformParser
from interoperability.transform_registry import TransformRegistry

CASE = Path(__file__).parent / 'integration' / 'fake_dnp3'
MODES = ('transform', 'driver')


def _rows(path: Path) -> list[dict]:
    with path.open() as f:
        return list(csv.DictReader(f))


def fake_driver_all_message(mode: str, **overrides) -> dict:
    def value(row):
        raw, kind = row['Starting Value'], row['Type']
        return float(raw) if kind == 'float' else int(raw) if kind == 'int' else raw == 'True' if kind == 'boolean' else raw
    message = {row['Volttron Point Name']: value(row) for row in _rows(CASE / f'{mode}_scaling' / 'fake_dnp3_der.fake.csv')
               if row['Starting Value'] != ''}
    message.update(overrides)
    return message


@pytest.fixture(scope='module')
def device():
    return discover_profile(CASE / 'profile_mandatory_1547.json')


@pytest.fixture(scope='module', params=MODES)
def mode(request):
    return request.param


@pytest.fixture(scope='module')
def config(mode) -> dict:
    return json.loads((CASE / f'{mode}_scaling' / 'presentation_config.json').read_text())


@pytest.fixture(scope='module')
def service(config):
    tree = UAITree()
    tree.ingest_mappings(config['mappings'])
    registry = TransformRegistry()
    for name, spec in config['formats'].items():
        registry.declare_format(name, hub=spec.get('hub'), fields=spec.get('fields'))
    bundled = resources.files('interoperability').joinpath('transforms')
    registry.update_registry([d for f in sorted(bundled.iterdir(), key=lambda f: f.name)
                              if f.is_file() and f.name.endswith('.json') for d in json.loads(f.read_text())]
                             + config['transforms'])
    return tree, registry


def resolve(service, uai: list[str]):
    tree, registry = service
    node, as_format = tree.resolve(tuple(uai))
    assert node is not None and node.is_canonical
    resource = node.resource.model_dump()
    chain, retention, path = registry.lookup_scored(resource['data_format'], as_format)
    return resource, as_format, path, retention, TransformParser().build_transform_from_schema(chain)


# ---- discovery and generation ----

def test_profile_discovery_reads_the_point_set(device):
    assert device.profile_name == 'profile_mandatory_1547' and device.notes == []
    assert {t: sum(1 for p in device.points if p.table == t) for t in ('AI', 'AO', 'BI', 'BO', 'CTR')} == {
        'AI': 55, 'AO': 42, 'BI': 19, 'BO': 7, 'CTR': 4}
    by_name = {p.name: p for p in device.points}
    assert by_name['AI_2'].uid == 'DGEN.VMinRtg' and by_name['AI_2'].multiplier == 0.1 and by_name['AI_2'].units == 'Volts'
    assert by_name['AO_217'].uid == 'DVVR.VVArCrv' and by_name['AO_217'].writable and not by_name['AI_2'].writable
    assert by_name['AI_328'].uid == 'DGSMn.InCrv'                                    # curve edit window selector
    # Any index listing works as a source, e.g. an integrity poll; unknown indexes are reported, not silently kept.
    polled = discover_indexes({'AI': [2, 3, 99999], 'BO': [3]}, values={'AI_2': 2400})
    assert [p.name for p in polled.points] == ['AI_2', 'AI_3', 'BO_3'] and polled.points[0].value == 2400
    assert polled.notes == ["'AI_99999': AI index 99999 is not in the IEEE 1815.2 point list"]


def test_generated_case_is_current(device, mode):
    out = CASE / f'{mode}_scaling'
    assert _rows(out / 'fake_dnp3_der.fake.csv') == [{k: str(v) for k, v in r.items()} for r in fake_registry_rows(device, mode)]
    assert _rows(out / 'fake_dnp3_der.dnp3.csv') == [{k: str(v) for k, v in r.items()} for r in dnp3_registry_rows(device, mode)]
    config = json.loads((out / 'presentation_config.json').read_text())
    assert config['formats']['fake_dnp3_der'] == {'hub': False, 'scaling': mode, 'fields': sorted(device.point_names)}
    assert config['transforms'] == dnp3_device_transforms('fake_dnp3_der', device.point_names, scaling=mode).definitions
    assert [(d['input_format'], d['output_format']) for d in config['transforms']] == [
        ('fake_dnp3_der', '1815.2.inputs'), ('fake_dnp3_der', '1815.2.outputs'), ('1815.2.outputs', 'fake_dnp3_der')]
    dnp3 = json.loads((out / 'fake_dnp3_der.dnp3.device.json').read_text())
    assert dnp3['driver_type'] == 'dnp3' and dnp3['remote_config']['port'] == 20000 and dnp3['remote_config']['outstation_id'] == 1


def test_registries_reflect_the_scaling_mode(device):
    transform_rows = {r['Volttron Point Name']: r for r in dnp3_registry_rows(device, 'transform')}
    driver_rows = {r['Volttron Point Name']: r for r in dnp3_registry_rows(device, 'driver')}
    assert transform_rows['AI_2'] == {'Point Name': 'DGEN.VMinRtg', 'Volttron Point Name': 'AI_2', 'Group': 30, 'Variation': 6,
                                      'Index': 2, 'Scaling': 1, 'Units': 'Volts', 'Writable': 'FALSE', 'Transform': '',
                                      'Notes': 'Nameplate Minimum Voltage Rating'}
    assert driver_rows['AI_2']['Scaling'] == 0.1 and driver_rows['AI_2']['Transform'] == 'scale(0.1)'
    assert driver_rows['AO_217']['Group'] == 40 and driver_rows['AO_217']['Transform'] == ''      # multiplier 1: nothing to apply
    assert {r['Volttron Point Name']: r['Group'] for r in dnp3_registry_rows(device, 'transform') if r['Volttron Point Name'] in ('BI_0', 'BO_3', 'CTR_5000')} == {'BI_0': 1, 'BO_3': 10, 'CTR_5000': 20}
    fake = {r['Volttron Point Name']: r for r in fake_registry_rows(device, 'transform')}
    assert fake['BI_0']['Type'] == 'boolean' and fake['CTR_5000']['Type'] == 'int' and fake['AI_2']['Type'] == 'int'


def test_point_names_and_profile_scaling():
    assert dnp3_point_path('AI_297') == ('AI', '297') and dnp3_point_path('BO_16') == ('BO', '16')
    assert dnp3_scaling('AI_2') == (0.1, 0.0) and dnp3_scaling('AO_217') == (1.0, 0.0)
    for bad in ['AI297', 'XX_1', 'AI_99999', '701_W']:
        with pytest.raises(ValueError):
            dnp3_point_path(bad)
    read, readback, write = dnp3_device_transforms('dev', ['AI_2', 'AO_217', 'AO_88'], scaling='transform').definitions
    assert read['pattern'] == {'AI': {'2': 'transform[AI_2](scale(0.1))'}}
    assert readback['pattern']['AO']['88'] == 'transform[AO_88](scale(0.1))'
    assert write['pattern']['AO_88'] == 'transform[AO, 88](scale(10.0))' and write['pattern']['AO_217'] == 'transform[AO, 217]()'
    assert write['pattern']['sequence[#]']['*AO'] == "transform[#, AO](scale_fields('88:10.0'), prefix_keys('AO_'))"
    driver = dnp3_device_transforms('dev', ['AI_2', 'AO_88'], scaling='driver').definitions
    assert driver[0]['pattern'] == {'AI': {'2': 'transform[AI_2]()'}} and driver[2]['pattern']['sequence[#]']['*AO'] == "transform[#, AO](prefix_keys('AO_'))"


# ---- the device used through each alias ----

def test_device_read_as_1815_2_inputs_and_beyond(service, mode):
    raw = {'AI_2': 2110, 'AI_3': 2640} if mode == 'transform' else {'AI_2': 211.0, 'AI_3': 264.0}   # VMinRtg, VMaxRtg (x0.1)
    message = fake_driver_all_message(mode, **raw)
    tree, registry = service
    inputs = TransformParser().build_transform_from_schema(registry.lookup('fake_dnp3_der', '1815.2.inputs')).execute(message)
    assert inputs['AI']['2'] == 211.0 and inputs['AI']['3'] == 264.0 and set(inputs) == {'AI', 'BI', 'CTR'}
    resource, fmt, path, retention, pipeline = resolve(service, ['site1', 'der_2030_5'])
    assert fmt == '2030.5' and path[:2] == ['fake_dnp3_der', '1815.2.inputs']
    sep2 = pipeline.execute(message)
    assert sep2['DERCapability']['rtgMinV'] == 211.0 and sep2['DERCapability']['rtgMaxV'] == 264.0
    resource, fmt, path, retention, pipeline = resolve(service, ['site1', 'der_sunspec'])
    assert fmt == 'sunspec' and pipeline.execute(message)['702']['VMinRtg'] == 211.0
    resource, fmt, path, retention, pipeline = resolve(service, ['site1', 'der_61850'])
    assert fmt == '61850' and pipeline.execute(message)['DGEN']['VMinRtg'] == 211.0


def test_both_scaling_modes_yield_the_same_inputs_message():
    outputs = []
    for mode, raw in (('transform', {'AI_2': 2110}), ('driver', {'AI_2': 211.0})):
        config = json.loads((CASE / f'{mode}_scaling' / 'presentation_config.json').read_text())
        pattern = next(d['pattern'] for d in config['transforms'] if d['output_format'] == '1815.2.inputs')
        outputs.append(TransformParser().build_transform_from_schema(pattern).execute(fake_driver_all_message(mode, **raw)))
    assert outputs[0] == outputs[1]


def test_writes_reach_the_device_as_ordered_flat_batches(service, mode):
    tree, registry = service
    chain, retention, path = registry.lookup_scored('2030.5', 'fake_dnp3_der')
    assert path == ['2030.5', '1815.2.outputs', 'fake_dnp3_der']                     # never through the read-only inputs
    control = {'DERControl': {'opModMaxLimW': 80},
               'DERCurve': {'opModVoltVar': {'CurveData': [{'xvalue': 95, 'yvalue': 44}, {'xvalue': 105, 'yvalue': -44}]}}}
    out = TransformParser().build_transform_from_schema(chain).execute(control)
    limit = 800.0 if mode == 'transform' else 80        # AO 88 has multiplier 0.1: the device edge undoes it, or the driver will
    assert out['AO_88'] == limit
    batch = out['sequence'][0]
    assert list(batch)[:4] == ['AO_244', 'AO_245', 'AO_246', 'AO_249'] and list(batch)[-1] == 'AO_217'   # select, type, count, points, assign
    assert batch['AO_244'] == 1 and batch['AO_245'] == 2 and batch['AO_246'] == 2 and batch['AO_249'] == 95
    assert batch['AO_250'] == (440.0 if mode == 'transform' else 44)               # var point multiplier 0.1
    # The 61850 route to the device also carries its schedule entries as further batches.
    sched = {'FSCH': {'SchdEntr': [{'StrTm': 5, 'DWMX': {'LimW': 50}}]}, 'DFPF': {'PFGnTgt': 0.9}}
    via_61850 = TransformParser().build_transform_from_schema(registry.lookup('61850', 'fake_dnp3_der')).execute(sched)
    assert 'AO_88' not in via_61850                                                     # LimW inside the schedule, not immediate
    assert via_61850['AO_210'] == (900.0 if mode == 'transform' else 0.9) or via_61850.get('AO_210') is not None


def test_point_map_for_the_2030_5_agent(service):
    tree, registry = service
    rows, notes = ieee2030_5_point_map(registry, 'fake_dnp3_der')
    by_point = {r['Point Name']: r['Parameter Type'] for r in rows}
    assert by_point['AI_2'] == 'DERCapability::rtgMinV' and by_point['AI_3'] == 'DERCapability::rtgMaxV'
    assert all(r['Notes'].startswith('via 1815.2.inputs > 2030.5') for r in rows)
    assert any('nested attribute' in n for n in notes) and any('curve points' in n or 'configured elsewhere' in n for n in notes)


def test_2030_5_field_universe_follows_the_convention():
    universe = field_universe.models_provider('2030.5')
    assert ('DERCapability', 'rtgMaxW') in universe and ('DERCapability', 'rtgMaxW', 'multiplier') not in universe
    assert ('DERControl', 'opModFixedPFInjectW', 'displacement') in universe and ('DERControl', 'opModFreqDroop', 'dBOF') in universe
    assert ('DERCurve', 'opModVoltVar', 'CurveData', '*', 'xvalue') in universe and ('MirrorMeterReading', 'V', 'PhaseA') in universe
    assert ('DERControlList', '*', 'interval', 'start') in universe
