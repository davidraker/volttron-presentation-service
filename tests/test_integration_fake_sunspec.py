def test_device_used_as_sunspec(service, mode):
    resource, fmt, path, retention, pipeline = resolve(service, ['site1', 'pv_sunspec'])
    assert resource['data_format'] == 'fake_sunspec_pv' and fmt == 'sunspec' and path == ['fake_sunspec_pv', 'sunspec']
    sunspec = pipeline.execute(fake_driver_all_message(mode))
    assert sunspec['701']['W'] == 9800.0 and sunspec['701']['Hz'] == 60.01 and sunspec['701']['LNV'] == 240.0
    assert sunspec['704']['PFWInj'] == {'PF': 0.95, 'Ext': 1}
    assert len(sunspec['705']['Crv']) == 3                                       # every stored curve, not just the active one
    curve = sunspec['705']['Crv'][0]
    assert curve['ActPt'] == 4 and curve['Pt'][:2] == [{'V': 92.0, 'Var': 30.0}, {'V': 96.7, 'Var': 0.0}]
    assert sunspec['711']['Ctl'][0]['DbOf'] == 600.3
    if mode == 'transform':
        assert sunspec['705']['V_SF'] == -2                                      # raw factors travel along
    else:
        assert 'V_SF' not in sunspec['705']
    # Writes reproduce every published device point exactly, whichever side scales.
    tree, registry = service
    back = TransformParser().build_transform_from_schema(registry.lookup('sunspec', 'fake_sunspec_pv')).execute(sunspec)
    assert back == fake_driver_all_message(mode)


def test_both_scaling_modes_yield_the_same_sunspec_message():
    outputs = []
    for mode in MODES:
        config = json.loads((CASE / f'{mode}_scaling' / 'presentation_config.json').read_text())
        to_sunspec = next(d['pattern'] for d in config['transforms'] if d['output_format'] == 'sunspec')
        message = TransformParser().build_transform_from_schema(to_sunspec).execute(fake_driver_all_message(mode))
        outputs.append({m: {k: v for k, v in body.items() if not k.endswith('_SF')} for m, body in message.items()})
    assert outputs[0] == outputs[1]


