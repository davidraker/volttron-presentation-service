def test_discovery_reads_the_device(device):
    assert device.identity == {'Mn': 'SunSpecTest', 'Md': 'Test-1547-1', 'SN': 'sn-123456789', 'Vr': '1.2.3'}
    assert len(device.points) == 384 and device.notes == []
    assert device.scale_factors['705_V_SF'] == -2 and device.scale_factors['701_Hz_SF'] == -3
    by_name = {p.name: p for p in device.points}
    assert by_name['701_W'].address == 40070 + 10 and by_name['701_W'].type == 'int16' and by_name['701_W'].scale_factor == '701_W_SF'
    assert by_name['705_Crv1_Pt1_V'].scale_factor == '705_V_SF' and by_name['705_Crv1_Pt1_V'].writable
    assert by_name['1_Mn'].is_string and by_name['1_Mn'].size == 16
    assert sum(1 for p in device.points if p.name.startswith('705_Crv')) == 3 * (9 + 4 * 2)      # 3 curves, 4 points each


def test_generated_case_is_current(device, mode):
    """The checked-in files match what build_configs.py derives from the device description."""
    out = CASE / f'{mode}_scaling'
    assert _rows(out / 'fake_sunspec_pv.fake.csv') == [{k: str(v) for k, v in r.items()} for r in fake_registry_rows(device, mode)]
    assert _rows(out / 'fake_sunspec_pv.modbus.csv') == [{k: str(v) for k, v in r.items()} for r in modbus_registry_rows(device, mode)]
    config = json.loads((out / 'presentation_config.json').read_text())
    names = [r['Volttron Point Name'] for r in _rows(out / 'fake_sunspec_pv.fake.csv')]
    assert config['formats']['fake_sunspec_pv'] == {'hub': False, 'scaling': mode, 'fields': sorted(names)}
    assert config['transforms'] == sunspec_device_transforms('fake_sunspec_pv', names, scaling=mode,
                                                             scale_factors=device.scale_factors).definitions
    assert infer_scaling(_rows(out / 'fake_sunspec_pv.modbus.csv')) == mode
    assert (out / 'store_configs.sh').read_text().count('vctl config store') == 3


def test_registries_reflect_the_scaling_mode(device):
    transform_rows = {r['Volttron Point Name']: r for r in modbus_registry_rows(device, 'transform')}
    driver_rows = {r['Volttron Point Name']: r for r in modbus_registry_rows(device, 'driver')}
    assert '701_W_SF' in transform_rows and '701_W_SF' not in driver_rows          # SF points only when the transform scales
    assert transform_rows['701_Hz']['Transform'] == '' and driver_rows['701_Hz']['Transform'] == 'scale_reg_pow_10(701_Hz_SF)'
    assert transform_rows['701_Hz']['Data Type'] == 'UINT32' and transform_rows['701_Hz']['Point Address'] == 40070 + 17
    assert transform_rows['1_Mn']['Data Type'] == 'string[32]'
    fake_transform = {r['Volttron Point Name']: r for r in fake_registry_rows(device, 'transform')}
    fake_driver = {r['Volttron Point Name']: r for r in fake_registry_rows(device, 'driver')}
    assert fake_transform['701_Hz']['Starting Value'] == 60010 and fake_driver['701_Hz']['Starting Value'] == 60.01
    assert fake_transform['705_Crv1_Pt1_V']['Starting Value'] == 9200 and fake_driver['705_Crv1_Pt1_V']['Starting Value'] == 92.0


def test_point_names_scale_factors_and_underscored_names():
    assert sunspec_point_path('705_Crv1_Pt3_Var') == ('705', 'Crv', 0, 'Pt', 2, 'Var')
    assert sunspec_point_path('708_Crv1_MustTrip_Pt1_V') == ('708', 'Crv', 0, 'MustTrip', 'Pt', 0, 'V')
    assert sunspec_point_path('701_TotWh_SF') == ('701', 'TotWh_SF')                 # underscore inside a SunSpec name
    assert sunspec_scale_factor('705_Crv1_Pt1_V') == '705_V_SF' and sunspec_scale_factor('705_Crv1_Pt1_Var') == '705_DeptRef_SF'
    assert sunspec_scale_factor('701_W') == '701_W_SF' and sunspec_scale_factor('705_Ena') is None
    assert is_scale_factor_point('701_W_SF') and not is_scale_factor_point('701_W')
    for bad in ['999_W', '701_Nope', '705_Crv_ActPt', '705_Crv1_Pt1', '701_W1', '701_W_Extra']:
        with pytest.raises(ValueError):
            sunspec_point_path(bad)


def test_device_transforms_scale_where_the_mode_says():
    names = ['701_W', '701_W_SF', '705_Crv1_ActPt', '705_Crv1_Pt1_V', '705_Crv1_Pt1_Var', '705_V_SF', '705_DeptRef_SF']
    by_transform = sunspec_device_transforms('dev', names, scaling='transform', scale_factors={'701_W_SF': 1, '705_V_SF': -2})
    read, write = by_transform.definitions
    assert read['pattern']['701']['W'] == "transform[701_W](scale_reg_pow_10('/701_W_SF'))"
    assert read['pattern']['705']['Crv[#] 1']['Pt[#]']['V'] == "transform[#, V](scale_reg_pow_10('/705_V_SF'))"
    assert write['pattern']['701_W'] == 'transform[701, W](scale(0.1))'
    assert "scale_fields('V:100.0')" in write['pattern']['*705_Crv_0_Pt']
    assert by_transform.notes == ['705_Crv1_Pt1_Var: scale factor 705_DeptRef_SF was not discovered; write left unscaled']
    by_driver = sunspec_device_transforms('dev', names, scaling='driver')
    read, write = by_driver.definitions
    assert read['pattern']['701'] == {'W': 'transform[701_W]()'} and '705_V_SF' not in json.dumps(read['pattern'])
    assert write['pattern']['701_W'] == 'transform[701, W]()' and by_driver.notes == []
    with pytest.raises(ValueError):
        sunspec_device_transforms('dev', names, scaling='magic')


