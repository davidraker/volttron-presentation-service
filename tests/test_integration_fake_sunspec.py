"""Integration: a SunSpec inverter discovered with pysunspec2, driven by the fake driver and used through
SunSpec, IEEE 2030.5 and IEEE 1815.2, with scale factors applied either by the transform or by the driver.

Exercises the same path the presentation service takes for an aliased resource: the mapping engine
resolves the alias to the canonical device and its format, the registry finds the chain from the
device's own format through ``sunspec`` to the alias format, and the compiled chain is applied to a
message shaped like the platform driver's ``devices/.../all`` publish. Everything under
``tests/integration/fake_sunspec/<mode>_scaling/`` is generated by ``build_configs.py`` from the
pysunspec2 device description ``device_1547.json``.
"""
from __future__ import annotations

